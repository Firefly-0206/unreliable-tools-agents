# The original cells and contrasts are asserted identical to the score files read above.
K2_MODELS = {"terra": ("score_codex_terra_k2decomp.json", "codex_terra_medium_k2decomp.jsonl"),
             "flash": ("score_ds_chat_fc_k2decomp.json", "ds_chat_fc_k2decomp.jsonl")}
# K2r = same-JSON executor replay (agentenv/k2e_replay.py, no LLM call): the JSON of each K2e episode, exact planner acts.
# Scored by score.py into score_*_k2replay.json, which is a strict superset of score_*_k2decomp.json (asserted below).
K2R_MODELS = {"terra": ("score_codex_terra_k2replay.json", "codex_terra_k2e_replay.jsonl"),
              "flash": ("score_ds_chat_fc_k2replay.json", "ds_chat_fc_k2e_replay.jsonl")}
NEWC = ["K2a", "K1e", "K2e", "K2p", "K2r"]
K2ROWS = ["K1", "K2", "K2a", "K2e", "K2r", "K1e", "K2p"]
COND_W.update({"K2a": "KTwoA", "K1e": "KOneE", "K2e": "KTwoE", "K2p": "KTwoP", "K2r": "KTwoR"})
K2FAMS = ["PERSIST", "SHARED", "MIXED", "TRANSIENT", "TRANSIENT_P"]
K2CONTR = [("K2a", "K1"), ("K2a", "K2"), ("K2e", "K2"), ("K2p", "K2"), ("K2p", "K1"), ("K1e", "K1"), ("K2e", "K1e"), ("K2p", "K2e"),
           ("K2r", "K2e"), ("K2r", "K1"), ("K2r", "K2p"), ("K2r", "K2"), ("K2r", "K1e")]
K2LAB = {"K1": "K1 (exact model stated)", "K2": "K2 (documentation only)", "K2a": "K2a (K2 + stated observation model)",
         "K2e": "K2e (K2, model first)", "K1e": "K1e (K1, model first)", "K2p": "K2p (K2e prompt, exact planner acts)",
         "K2r": "K2r (K2e's own JSON, exact planner acts)"}
REC_M = [("struct_exact", "Struct", "pct"), ("pair_ok", "Pair", "pct"), ("single_ok", "Single", "pct"), ("bits_correct", "Bits", "pct"),
         ("fault_present_ok", "FaultOk", "pct"), ("persistent_ok", "PersOk", "pct"), ("phi_abs_err", "PhiErr", "d3"),
         ("phantom_fault", "Phantom", "pct"), ("parse_ok", "Parse", "pct"), ("fallback", "Fallback", "pct"),
         ("n_defaults", "Defaults", "d2"), ("regret_if_struct_exact", "RegExact", "d2"), ("regret_if_struct_wrong", "RegWrong", "d2")]
K2 = {}
PR2 = {}
for tag, pre, disp, sf, lf, kp in MODELS:
    kf, klf = K2_MODELS[tag]
    KJ0 = json.load(open(os.path.join(AG, "results", kf), encoding="utf-8"))
    rf, rlf = K2R_MODELS[tag]
    KJ = json.load(open(os.path.join(AG, "results", rf), encoding="utf-8"))
    # the replay score file contains every cell / contrast / twin contrast / recovery pool of the k2decomp score file unchanged
    for sect in ("cells", "contrasts", "twin_contrasts_k2decomp", "recovery_core_pooled"):
        for k, v in KJ0[sect].items():
            assert KJ[sect][k] == v, (tag, sect, k)
    OJ = DATA[tag]["J"]
    # (1) the original cells and contrasts in the k2decomp score file equal the existing score file
    for k, v in OJ["cells"].items():
        for m, x in v.items():
            if isinstance(x, (int, float)) and not isinstance(x, bool):
                assert abs(KJ["cells"][k][m] - x) < 1e-9, (tag, k, m)
    for k, v in OJ["contrasts"].items():
        assert KJ["contrasts"][k] == v, (tag, k)
    # (2) re-score the combined logs and check every cell mean of the k2decomp file
    recs = {}
    for fn in (lf, klf, rlf):
        for line in open(os.path.join(AG, "logs", fn), encoding="utf-8"):
            r = json.loads(line)
            if r["status"].startswith("api_error"):
                continue
            recs[(r["episode"], r["condition"], r.get("sample", 0))] = r
    pr2 = collections.defaultdict(dict)
    for (ep, cd, _), r in recs.items():
        pr2[(r["family"], cd)][ep] = per_run(r, EPS[ep], TRUTH[ep])
    for key, c in KJ["cells"].items():
        fam, cd = key.split("|")[-2:]
        d = pr2[(fam, cd)]
        assert len(d) == c["n"], (tag, key, len(d), c["n"])
        for m in ("regret", "info", "rep_cache", "calls", "correct", "severe"):
            assert abs(float(np.mean([x[m] for x in d.values()])) - c[m]) < 1e-9, (tag, key, m)
    PR2[tag] = pr2
    K2[tag] = KJ
    print("k2decomp", tag, "original cells/contrasts identical to", sf, "; k2decomp score file contained unchanged in", rf,
          "; re-scored cells (incl. K2r) match", rf)


def k2cell(tag, fam, cd):
    return K2[tag]["cells"][f"{DATA[tag]['kp']}|{fam}|{cd}"]


def k2con(tag, fam, a, b):
    return K2[tag]["contrasts"].get(f"{DATA[tag]['kp']}|{fam}|{a}-{b}")


def k2twin(tag, key, cd):
    return K2[tag]["twin_contrasts_k2decomp"][f"{DATA[tag]['kp']}|{key}|{cd}"]


def k2pool(tag, fams, cd, m="regret"):
    v = {ep: x[m] for f in fams for ep, x in PR2[tag][(f, cd)].items()}
    ids = sorted(v)
    return nested_ci([v[i] for i in ids], ids, [SC[i] for i in ids])


def k2rec(tag, cd):
    return K2[tag]["recovery_core_pooled"][f"{DATA[tag]['kp']}|{cd}"]


def rfmt(v, kind):
    if v is None:
        return "--"
    return f"{100 * v:.0f}" if kind == "pct" else (f"{v:.3f}" if kind == "d3" else f"{v:.2f}")


