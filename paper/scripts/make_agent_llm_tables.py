def minus(s):
    s = s.replace("-0.00", "0.00")          # no negative zeros
    return s.replace("-", "$-$")


def sg(x, d=2):
    s = f"{x:+.{d}f}"
    return minus(s[1:] if float(s) == 0 else s)          # no signed zeros


def f2(x):
    return minus(f"{x:.2f}")


def ci3(m, lo, hi, signed=False):
    if signed:
        return minus(f"{m:+.2f} [{lo:+.2f}, {hi:+.2f}]")
    return minus(f"{m:.2f} [{lo:.2f}, {hi:.2f}]")


MAC = []


def mac(name, val, src):
    assert name.isalpha(), name
    MAC.append(f"\\providecommand{{\\{name}}}{{{val}}}% src: {src}")


def write(name, src, body):
    with open(os.path.join(OUT, name), "w", encoding="utf-8") as fh:
        fh.write(HDR.replace("%s", src) + body)
    print("wrote", name)


def sha256(p):
    h = hashlib.sha256()
    with open(p, "rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


