def ncon(tag, fam, a, b):
    """score-file contrast, or (terra high: K2e-K1 is not in the file) a paired nested bootstrap from the re-scored logs."""
    ct = NEWD[tag]["J"]["contrasts"].get(f"{NEWD[tag]['kp']}|{fam}|{a}-{b}")
    if ct is not None:
        return ct["regret"]
    fams = CORE if fam == "CORE" else [fam]
    pa = {ep: x["regret"] for f in fams for ep, x in NEWD[tag]["pr"][(f, a)].items()}
