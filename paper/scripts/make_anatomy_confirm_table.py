import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(os.path.dirname(ROOT), "raea4", "agentenv", "results", "anatomy_confirm.json")
A = json.load(open(SRC, encoding="utf-8"))
RUNS = [("flash", "Flash"), ("terra", "Terra"), ("sonnet", "Sonnet")]
NL = chr(10)
BS = chr(92)
MINUS = "$-$"


def num(x, plus=False, nd=2):
    s = f"{abs(x):.{nd}f}"
    if float(s) == 0: return s
    return (MINUS if x < 0 else ("+" if plus else "")) + s


def ci(d, plus=False): return f"{num(d['mean'], plus)} [{num(d['lo'], plus)}, {num(d['hi'], plus)}]"
def pc(x): return f"{100 * x:.0f}"
def pci(d): return f"{num(100 * d['mean'], True, 0)} [{num(100 * d['lo'], True, 0)}, {num(100 * d['hi'], True, 0)}]"
def yes(o, c): return ("met" if o["met"][c] else "not met") if c in o["criteria"] else ("(" + ("met" if o["met"][c] else "not met") + ")")


mac, r1, r2 = [], [], []


def M(name, val, src):
    mac.append(BS + "providecommand{" + BS + "ac" + name + "}{" + str(val) + "}% src: anatomy_confirm.json:" + src)


for key, tag in RUNS:
    if key not in A: continue
    o = A[key]; F = o["first|FAULT"]; T = o["first|TWIN"]
    M(tag + "KTwoE", num(o["K2e"]["mean"]), f"{key}.K2e.mean"); M(tag + "KTwoECI", ci(o["K2e"]), f"{key}.K2e")
    M(tag + "KTwoR", num(o["K2r"]["mean"], nd=3), f"{key}.K2r.mean")
    M(tag + "GapCI", ci(o["K2r-K2e"], True), f"{key}.K2r-K2e")
    M(tag + "PassShare", pc(o["pass_share"]), f"{key}.pass_share")
    M(tag + "PassCI", ci(o["pass_cache"]), f"{key}.pass_cache"); M(tag + "Rest", num(o["rest"]["mean"]), f"{key}.rest.mean")
    M(tag + "PassMinusRestCI", ci(o["pass-rest"], True), f"{key}.pass-rest")
    M(tag + "FirstModel", pc(F["model"]["mean"]), f"{key}.first|FAULT.model"); M(tag + "FirstPlanner", pc(F["planner"]["mean"]), f"{key}.first|FAULT.planner")
    M(tag + "FirstDiffCI", pci(F["diff"]), f"{key}.first|FAULT.diff (percentage points)")
    M(tag + "FirstModelTwin", pc(T["model"]["mean"]), f"{key}.first|TWIN.model"); M(tag + "FirstPlannerTwin", pc(T["planner"]["mean"]), f"{key}.first|TWIN.planner")
    M(tag + "Verdict", num(o["verdict"]["mean"]), f"{key}.verdict.mean"); M(tag + "Over", num(o["over"]["mean"]), f"{key}.over.mean")
    M(tag + "Calls", num(o["calls"]["mean"]), f"{key}.calls.mean"); M(tag + "CallsPlanner", num(o["planner_calls"]), f"{key}.planner_calls")
    M(tag + "Usable", o["usable"], f"{key}.usable"); M(tag + "NoSubmit", o["no_submit"], f"{key}.no_submit")
    M(tag + "Confirms", "confirms" if o["confirms"] else "does not confirm", f"{key}.confirms")
    r1.append(f"{o['label']} & {o['usable']}/100 & {num(o['K2e']['mean'])} & {num(o['K2r']['mean'], nd=3)} & {ci(o['K2r-K2e'], True)} & {yes(o, 'C1')} & "
              f"{ci(o['pass_cache'])} & {num(o['rest']['mean'])} & {pc(o['pass_share'])} & {ci(o['pass-rest'], True)} & {yes(o, 'C2')} " + BS * 2)
    r2.append(f"{o['label']} & {pc(F['model']['mean'])} & {pc(F['planner']['mean'])} & {pci(F['diff'])} & {yes(o, 'C3')} & "
              f"{pc(T['model']['mean'])} & {pc(T['planner']['mean'])} & {num(o['over']['mean'])} & {num(o['verdict']['mean'])} & "
              f"{num(o['calls']['mean'])} / {num(o['planner_calls'])} & {'yes' if o['confirms'] else 'no'} " + BS * 2)

hdr = "% generated by scripts/make_anatomy_confirm_table.py from raea4/agentenv/results/anatomy_confirm.json; do not edit"
t1 = [hdr, BS + "begin{tabular}{@{}lcrrcccrrcc@{}}", BS + "toprule",
      " & & & & " + BS + "multicolumn{2}{c}{C1: K2r$-$K2e} & " + BS + "multicolumn{5}{c}{C2: replica tool passed over} " + BS * 2 + BS + "cmidrule(lr){5-6}" + BS + "cmidrule(lr){7-11}",
      "Run & Usable & K2e & K2r & diff.~[95" + BS + "% CI] & & regret [95" + BS + "% CI] & rest & share " + BS + "% & passed$-$rest [95" + BS + "% CI] & " + BS * 2,
      BS + "midrule"] + r1 + [BS + "bottomrule", BS + "end{tabular}"]
t2 = [hdr, BS + "begin{tabular}{@{}lrrccrrrrcc@{}}", BS + "toprule",
      " & " + BS + "multicolumn{4}{c}{C3: first call is a replica tool, fault families (" + BS + "%)} & " + BS + "multicolumn{2}{c}{twin (" + BS + "%)} & & & & " + BS * 2 + BS + "cmidrule(lr){2-5}" + BS + "cmidrule(lr){6-7}",
      "Run & model & planner & diff.~[95" + BS + "% CI], pp & & model & planner & over-probe & verdict & calls (model / planner) & confirms " + BS * 2,
      BS + "midrule"] + r2 + [BS + "bottomrule", BS + "end{tabular}"]
open(os.path.join(ROOT, "tables", "agent_anatomy_confirm.tex"), "w", encoding="utf-8").write(NL.join(t1) + NL)
open(os.path.join(ROOT, "tables", "agent_anatomy_confirm_use.tex"), "w", encoding="utf-8").write(NL.join(t2) + NL)
open(os.path.join(ROOT, "tables", "nums_anatomy_confirm.tex"), "w", encoding="utf-8").write(hdr + NL + NL.join(mac) + NL)
print(NL.join(mac)); print(NL.join(t1)); print(NL.join(t2))
