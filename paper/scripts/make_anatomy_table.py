"""tables/agent_anatomy.tex and tables/nums_anatomy.tex from raea4/agentenv/results/k2e_anatomy.json
(written by raea4/agentenv/k2e_anatomy.py: exact per-step oracle advantages of the stored K2e / K1 trajectories,
split by kind of lossy step; no model call).

    python paper/scripts/make_anatomy_table.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(os.path.dirname(ROOT), "raea4", "agentenv", "results", "k2e_anatomy.json")
A = json.load(open(SRC, encoding="utf-8"))
RUNS = [("flash", "Flash", "flash (non-thinking)"), ("terra", "Terra", "gpt-6.1-terra (medium)"),
        ("terra_high", "TerraHigh", "gpt-6.1-terra (high)"), ("sonnet", "Sonnet", "Sonnet 5.5 (high)")]
NL = chr(10)


def f2(x): return f"{x:.2f}"
def ci(q, m): return f"{q[m]:.2f} [{q[m + '_lo']:.2f}, {q[m + '_hi']:.2f}]"
def pc(x): return "--" if x is None else f"{100 * x:.0f}"


mac, rows, rows3 = [], [], []


def M(name, val, src):
    mac.append("\\providecommand{\\an" + name + "}{" + str(val) + "}% src: k2e_anatomy.json:" + src)


for key, tag, label in RUNS:
    a = A[key]; P = a["pass"]
    M(tag + "Regret", f2(a["regret"]), f"{key}.regret")
    M(tag + "PassShare", pc(P["K2e|CORE"]["pass_cache_share"]), f"{key}.pass[K2e|CORE].pass_cache_share")
    M(tag + "PassShareKOne", pc(P["K1|CORE"]["pass_cache_share"]), f"{key}.pass[K1|CORE].pass_cache_share")
    M(tag + "PassCI", ci(P["K2e|CORE"], "pass_cache"), f"{key}.pass[K2e|CORE].pass_cache")
    M(tag + "PassOtherFault", f2(P["K2e|FAULT"]["pass_cache_other"]), f"{key}.pass[K2e|FAULT].pass_cache_other")
    M(tag + "PassOtherTwin", f2(P["K2e|TWIN"]["pass_cache_other"]), f"{key}.pass[K2e|TWIN].pass_cache_other")
    M(tag + "Verdict", f2(a["verdict"]), f"{key}.verdict")
    M(tag + "Over", f2(a["over"]), f"{key}.over")
    M(tag + "OverShare", pc(a["over_share"]), f"{key}.over_share")
    M(tag + "VerdictShare", pc(a["verdict_share"]), f"{key}.verdict_share")
    M(tag + "Calls", f2(a["calls"]), f"{key}.calls")
    M(tag + "CallsPlanner", f2(a["k2r_calls"]), f"{key}.k2r_calls")
    M(tag + "ZeroShare", pc(a["zero"]), f"{key}.zero")
    M(tag + "RelLoss", pc(a["regret"] / a["V0"]), f"{key}.regret / {key}.V0")
    U = a["use"]
    M(tag + "FirstCache", pc(U["K2e|FAULT"]["first_cache"]), f"{key}.use[K2e|FAULT].first_cache")
    M(tag + "UsedCache", pc(U["K2e|FAULT"]["used_cache"]), f"{key}.use[K2e|FAULT].used_cache")
    M(tag + "FirstCacheTwin", pc(U["K2e|TWIN"]["first_cache"]), f"{key}.use[K2e|TWIN].first_cache")
    M(tag + "PlannerFirstCache", pc(U["K2r|FAULT"]["first_cache"]), f"{key}.use[K2r|FAULT].first_cache")
    M(tag + "PlannerUsedCache", pc(U["K2r|FAULT"]["used_cache"]), f"{key}.use[K2r|FAULT].used_cache")
    for cond, cl in [("K2e", "the model, own JSON (K2e)"), ("K2r", "exact planner, same JSON (K2r)"), ("K1", "the model, model stated (K1)")]:
        for sub, sl in [("FAULT", "fault families"), ("TWIN", "fault-free twin")]:
            q = U[cond + "|" + sub]
            first = (label if (cond, sub) == ("K2e", "FAULT") else "")
            rows3.append(f"{first} & {cl} & {sl} & {q['n']} & {pc(q['used_cache'])} [{pc(q['used_cache_lo'])}, {pc(q['used_cache_hi'])}] & "
                         f"{pc(q['first_cache'])} & {f2(q['cache_calls'])} & {f2(q['other_calls'])} \\\\")
    rows3.append("\\addlinespace")
    for cond in ["K2e", "K1"]:
        for sub, sl in [("CORE", "CORE"), ("FAULT", "fault families"), ("TWIN", "fault-free twin")]:
            q = P[cond + "|" + sub]
            first = (label if (cond, sub) == ("K2e", "CORE") else "")
            rows.append(f"{first} & {cond} & {sl} & {q['n']} & {f2(q['regret'])} & {ci(q, 'pass_cache')} & "
                        f"{f2(q['pass_cache_other'])} & {f2(q['pass_cache_stop'])} & {f2(q['rest'])} & {pc(q['pass_cache_share'])} \\\\")
    rows.append("\\addlinespace")
M("OracleLoss", f2(A["terra"]["V0"]), "terra.V0 (same episodes for every run)")

rows = rows[:-1]
tab = ["% generated by scripts/make_anatomy_table.py from raea4/agentenv/results/k2e_anatomy.json; do not edit",
       "\\begin{tabular}{@{}lllrrcrrrr@{}}", "\\toprule",
       " & & & & & \\multicolumn{3}{c}{replica tool passed over} & & \\\\\\cmidrule(lr){6-8}",
       "Run & Cond. & Episodes & $n$ & Regret & total [95\\% CI] & other source & stopped & Rest & Share \\% \\\\", "\\midrule"]
tab += rows + ["\\bottomrule", "\\end{tabular}"]
open(os.path.join(ROOT, "tables", "agent_anatomy.tex"), "w", encoding="utf-8").write(NL.join(tab) + NL)

rows2 = []
for key, tag, label in RUNS:
    a = A[key]
    rows2.append(f"{label} & {f2(a['regret'])} & {f2(a['over'])} & {f2(a['wrong'])} & {f2(a['early'])} & {f2(a['verdict'])} & "
                 f"{a['n_over_rep']}/{a['n_over']} & {f2(a['calls'])} & {f2(a['k2r_calls'])} & {pc(a['zero'])} \\\\")
tab2 = ["% generated by scripts/make_anatomy_table.py from raea4/agentenv/results/k2e_anatomy.json; do not edit",
        "\\begin{tabular}{@{}lrrrrrcrrr@{}}", "\\toprule",
        "Run & Regret & Over-probe & Wrong tool & Early stop & Verdict & Rep./over & Calls & Planner calls & Zero-regret \\% \\\\",
        "\\midrule"] + rows2 + ["\\bottomrule", "\\end{tabular}"]
open(os.path.join(ROOT, "tables", "agent_anatomy_steps.tex"), "w", encoding="utf-8").write(NL.join(tab2) + NL)
tab3 = ["% generated by scripts/make_anatomy_table.py from raea4/agentenv/results/k2e_anatomy.json; do not edit",
        "\\begin{tabular}{@{}lllrcrrr@{}}", "\\toprule",
        "Run & Executor & Episodes & $n$ & Any replica call \\% [95\\% CI] & First call replica \\% & Replica calls & Other calls \\\\",
        "\\midrule"] + rows3[:-1] + ["\\bottomrule", "\\end{tabular}"]
open(os.path.join(ROOT, "tables", "agent_anatomy_use.tex"), "w", encoding="utf-8").write(NL.join(tab3) + NL)
open(os.path.join(ROOT, "tables", "nums_anatomy.tex"), "w", encoding="utf-8").write(
    "% generated by scripts/make_anatomy_table.py; do not edit" + NL + NL.join(mac) + NL)
print(NL.join(mac)); print(NL.join(tab)); print(NL.join(tab2))
