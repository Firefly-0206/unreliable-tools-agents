"""Macros and appendix tables of the belief-elicitation experiment (raea4/agentenv/PLAN_be_belief_elicit.md).
Sources: raea4/agentenv/results/be_analysis.json (be_analysis.py, planned), results/be_posthoc.json (be_posthoc.py, POST HOC),
logs/be_*.jsonl (row counts, finish reasons). Writes tables/nums_be.tex, tables/agent_be.tex, tables/agent_be_posthoc.tex."""
import json, os
from collections import Counter
HERE = os.path.dirname(os.path.abspath(__file__))
AG = os.path.join(HERE, "..", "..", "raea4", "agentenv")
d = json.load(open(os.path.join(AG, "results", "be_analysis.json")))
ph = json.load(open(os.path.join(AG, "results", "be_posthoc.json")))
RUNS = [("flash", "Flash", "be_ds_chat_fc.jsonl"), ("terra", "Terra", "be_codex_terra.jsonl"), ("sonnet", "Sonnet", "be_claude_s55.jsonl")]

def sgn(x, nd): return ("+" if round(x, nd) > 0 else "$-$" if round(x, nd) < 0 else "") + f"{abs(x):.{nd}f}"
def iv(c, nd=2, signed=True, scale=1.0):
    f = (lambda x: sgn(scale * x, nd)) if signed else (lambda x: f"{scale * x:.{nd}f}")
    return f"{f(c['mean'])} [{f(c['lo'])}, {f(c['hi'])}]"
def pct(c, signed=False): return iv(c, 0, signed, 100.0)

out = ["% generated by scripts/make_be_outputs.py; do not edit"]
def mac(name, val, src): out.append(f"\\providecommand{{\\be{name}}}{{{val}}}% src: {src}")

tot_rows = 0; n_err = 0
for key, M, fn in RUNS:
    r = d[key]; S = r["stats"]; P = ph[key]
    rows = [json.loads(l) for l in open(os.path.join(AG, "logs", fn), encoding="utf-8")]
    tot_rows += len(rows); n_err += sum(x["status"] != "ok" for x in rows)
    fin = Counter((x["fork"], x.get("finish_reason")) for x in rows)
    mac(f"{M}Points", r["n"], f"be_analysis.json:{key}.n")
    for l in "UOR": mac(f"{M}N{l}", r["labels"][l], f"be_analysis.json:{key}.labels.{l}")
    mac(f"{M}BFound", S["B found"], f"{key} B found")
    mac(f"{M}BRepaired", S["B repaired (closing braces appended)"], f"{key} B repaired"); mac(f"{M}CRepaired", S["C repaired"], f"{key} C repaired")
    mac(f"{M}BLength", fin[("B", "length")], f"logs/{fn} finish length B"); mac(f"{M}CLength", fin[("C", "length")], f"logs/{fn} finish length C")
    mac(f"{M}Unusable", S["points with unusable JSON"], f"{key} unusable JSON")
    mac(f"{M}TVU", iv(S["B1 tv_json | U"], 3, False), f"{key} B1 tv_json U"); mac(f"{M}TVO", iv(S["B1 tv_json | O"], 3, False), f"{key} B1 tv_json O")
    mac(f"{M}TVDiff", iv(S["B2 tv_json U-O"], 3), f"{key} B2 tv_json"); mac(f"{M}StaleU", iv(S["B1 stale_err_json | U"], 3, False), f"{key} B1 stale U")
    mac(f"{M}StaleDiff", iv(S["B2 stale_err_json U-O"], 3), f"{key} B2 stale"); mac(f"{M}PredU", iv(S["B1 pred_tv | U"], 3, False), f"{key} B1 pred U")
    mac(f"{M}LogU", iv(S["B1 logscore | U"], 2), f"{key} logscore U"); mac(f"{M}LogO", iv(S["B1 logscore | O"], 2), f"{key} logscore O")
    mac(f"{M}LogDiff", iv(S["B2 logscore U-O"], 2), f"{key} logscore U-O")
    mac(f"{M}RhoU", iv(S["B1 rho_json | U"]), f"{key} rho_json U"); mac(f"{M}RhoO", iv(S["B1 rho_json | O"]), f"{key} rho_json O")
    mac(f"{M}RhoUN", S["B1 rho_json | U"]["n"], f"{key} rho_json U n"); mac(f"{M}RhoDiff", iv(S["B2 rho_json U-O"]), f"{key} rho U-O")
    mac(f"{M}RankBelow", pct(S["B3 rank_below | U"]), f"{key} rank_below U"); mac(f"{M}RepBias", iv(S["B3 rep_bias_json | U"]), f"{key} rep_bias_json U")
    mac(f"{M}RepBiasN", S["B3 rep_bias_json | U"]["n"], f"{key} rep_bias_json U n")
    mac(f"{M}Agree", pct(S["B4 agree | all"]), f"{key} B4 all"); mac(f"{M}AgreeU", pct(S["B4 agree | U"]), f"{key} B4 U")
    mac(f"{M}AgreeMean", f"{100 * S['B4 agree | all']['mean']:.0f}", f"{key} B4 all mean")
    mac(f"{M}ARep", f"{100 * S['fork A replica | U']['mean']:.0f}", f"{key} fork A replica U"); mac(f"{M}CRep", f"{100 * S['fork C replica | U']['mean']:.0f}", f"{key} fork C replica U")
    mac(f"{M}CA", pct(S["B5 replica C-A | U"], True), f"{key} B5"); mac(f"{M}CAN", S["B5 n paired (both parsed)"], f"{key} B5 n")
    # post hoc
    mac(f"{M}OneStep", iv(P["P1 stated - VOI1 (one-step) | U replica"]), f"be_posthoc.json:{key} P1 voi1")
    mac(f"{M}Closer", f"{100 * P['P1 share closer to VOI1 than to VOI | U replica']['mean']:.0f}", f"{key} P1 closer")
    a, b, c = [int(x) for x in P["P1 all tools, all points: within 0.06 of VOI1 / of VOI / tools"].split(" / ")]
    mac(f"{M}NearOne", a, f"{key} P1 near"); mac(f"{M}NearMulti", b, f"{key} P1 near"); mac(f"{M}NearTools", c, f"{key} P1 near")
    mac(f"{M}RhoOneU", iv(P["P2 rho(stated, VOI1) | U"]), f"{key} P2"); mac(f"{M}RhoOneO", iv(P["P2 rho(stated, VOI1) | O"]), f"{key} P2")
    mac(f"{M}RhoEnvU", iv(P["P2 rho(VOI1, VOI), no model | U"]), f"{key} P2 env"); mac(f"{M}RhoEnvO", iv(P["P2 rho(VOI1, VOI), no model | O"]), f"{key} P2 env")
    mac(f"{M}Argmax", pct(P["P3 ... | U"]), f"{key} P3 U"); mac(f"{M}ArgmaxN", P["P3 ... | U"]["n"], f"{key} P3 U n")
if True:
    P = ph["flash"]
    mac("FlashRepBiasNoRep", iv(P["P4 B3 rep_bias_json | U, repaired rows excluded"]), "flash P4 repaired excluded")
    mac("FlashRepBiasNoRepN", P["P4 B3 rep_bias_json | U, repaired rows excluded"]["n"], "flash P4 n")
    mac("FlashRepBiasNoLater", iv(P["P4 B3 rep_bias_json | U, turns with a later replica call excluded"]), "flash P4 later")
    mac("FlashRepBiasNoLaterN", P["P4 B3 rep_bias_json | U, turns with a later replica call excluded"]["n"], "flash P4 later n")
    mac("FlashAgreeAny", iv(P["P4 B4 agree | all, logged first call anywhere among fork A's calls"], 1, False, 100.0), "flash P4 agree any")
    mac("FlashCNoAct", pct(P["P4 fork C gave no action | U"]), "flash P4 C no action")
    mac("FlashCAMissing", pct(P["P4 B5 replica C-A | U, missing C action = no replica (all U)"], True), "flash P4 B5 missing")
    mac("FlashCAAny", pct(P["P4 B5 replica C-A | U, replica = any call of the turn, missing = no"], True), "flash P4 B5 any")
    T5 = ph["terra"]; nu = lambda g: [int(x) for x in T5[f"P5 all-null values | {g}"].split("/")]
    u, o, c0, c1 = nu("U"), nu("O"), nu("calls_before 0"), nu("calls_before 1")
    mac("TerraNullU", f"{u[0]} of {u[1]}", "terra P5 U"); mac("TerraNullO", f"{o[0]} of {o[1]}", "terra P5 O")
    mac("TerraNullEarly", f"{c0[0] + c1[0]} of {c0[1] + c1[1]}", "terra P5 calls_before 0-1")
mac("Rows", f"{tot_rows:,}".replace(",", "{,}"), "logs/be_*.jsonl"); mac("Errors", n_err, "logs/be_*.jsonl status")

def row(label, f):
    return label + " & " + " & ".join(f(k) for k, _, _ in RUNS) + " \\\\"
S = {k: d[k]["stats"] for k, _, _ in RUNS}; P = {k: ph[k] for k, _, _ in RUNS}
def withn(c, fmt): return f"{fmt(c)} ({c['n']})"
plan = [
    row("decision points: U / O / R", lambda k: f"{d[k]['labels']['U']} / {d[k]['labels']['O']} / {d[k]['labels']['R']}"),
    row("fork B: belief parsed (repaired)", lambda k: f"{S[k]['B found']} ({S[k]['B repaired (closing braces appended)']})"),
    "\\midrule",
    row("B1 status TV at U", lambda k: iv(S[k]["B1 tv_json | U"], 3, False)),
    row("B1 status TV at O", lambda k: iv(S[k]["B1 tv_json | O"], 3, False)),
    row("B2 status TV, U $-$ O", lambda k: iv(S[k]["B2 tv_json U-O"], 3)),
    row("B1 stale-probability error at U", lambda k: iv(S[k]["B1 stale_err_json | U"], 3, False)),
    row("B2 stale-probability error, U $-$ O", lambda k: iv(S[k]["B2 stale_err_json U-O"], 3)),
    row("B1 next-report TV at U", lambda k: iv(S[k]["B1 pred_tv | U"], 3, False)),
    "\\midrule",
    row("B3 rank correlation with $\\mathrm{VOI}$ at U ($n$)", lambda k: withn(S[k]["B1 rho_json | U"], iv)),
    row("B3 rank correlation with $\\mathrm{VOI}$ at O ($n$)", lambda k: withn(S[k]["B1 rho_json | O"], iv)),
    row("B3 replica stated below logged action, U (\\%)", lambda k: pct(S[k]["B3 rank_below | U"])),
    row("B3 replica: stated $-$ $\\mathrm{VOI}$, U ($n$)", lambda k: withn(S[k]["B3 rep_bias_json | U"], iv)),
    "\\midrule",
    row("B4 fork A = logged action, all (\\%)", lambda k: pct(S[k]["B4 agree | all"])),
    row("B4 fork A = logged action, U (\\%)", lambda k: pct(S[k]["B4 agree | U"])),
    row("B5 replica share at U, C $-$ A (points; $n$)", lambda k: withn(S[k]["B5 replica C-A | U"], lambda c: pct(c, True))),
]
post = [
    row("replica at U: stated $-$ $\\mathrm{VOI}_1$", lambda k: iv(P[k]["P1 stated - VOI1 (one-step) | U replica"])),
    row("replica at U: closer to $\\mathrm{VOI}_1$ than to $\\mathrm{VOI}$ (\\%)", lambda k: pct(P[k]["P1 share closer to VOI1 than to VOI | U replica"])),
    row("all stated values within 0.06 of $\\mathrm{VOI}_1$ / of $\\mathrm{VOI}$", lambda k: P[k]["P1 all tools, all points: within 0.06 of VOI1 / of VOI / tools"].replace(" / ", " / ", 1).rsplit(" / ", 1)[0] + " of " + P[k]["P1 all tools, all points: within 0.06 of VOI1 / of VOI / tools"].rsplit(" / ", 1)[1]),
    row("rank correlation, stated with $\\mathrm{VOI}_1$, U", lambda k: iv(P[k]["P2 rho(stated, VOI1) | U"])),
    row("rank correlation, stated with $\\mathrm{VOI}_1$, O", lambda k: iv(P[k]["P2 rho(stated, VOI1) | O"])),
    row("rank correlation, $\\mathrm{VOI}_1$ with $\\mathrm{VOI}$ (no model), U", lambda k: iv(P[k]["P2 rho(VOI1, VOI), no model | U"])),
    row("rank correlation, $\\mathrm{VOI}_1$ with $\\mathrm{VOI}$ (no model), O", lambda k: iv(P[k]["P2 rho(VOI1, VOI), no model | O"])),
    row("fork C action = argmax of its stated values, U (\\%; $n$)", lambda k: withn(P[k]["P3 ... | U"], pct)),
]
T = os.path.join(HERE, "..", "tables")
open(os.path.join(T, "nums_be.tex"), "w").write("\n".join(out) + "\n")
head = ["\\begin{tabular}{@{}llll@{}}", "\\toprule", " & Flash & Terra & Sonnet \\\\", "\\midrule"]
open(os.path.join(T, "agent_be.tex"), "w").write("\n".join(
    ["% generated by scripts/make_be_outputs.py from raea4/agentenv/results/be_analysis.json; do not edit"] + head + plan + ["\\bottomrule", "\\end{tabular}"]) + "\n")
open(os.path.join(T, "agent_be_posthoc.tex"), "w").write("\n".join(
    ["% generated by scripts/make_be_outputs.py from raea4/agentenv/results/be_posthoc.json (post hoc); do not edit"] + head + post + ["\\bottomrule", "\\end{tabular}"]) + "\n")
print(f"{len(out) - 1} macros")
