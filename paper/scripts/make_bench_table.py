"""Exact reference policies of the single-decision benchmark -> tables/bench_reference.tex

Reads  raea4/bench/results/reference_policies.json
    python paper/scripts/make_bench_table.py
"""
import json
import os

SRC = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))), "raea4", "bench", "results", "reference_policies.json")
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "tables")
os.makedirs(OUT, exist_ok=True)
J = json.load(open(SRC, encoding="utf-8"))

# json key, label.  Discarding existing history and forbidding future calls are kept apart in the labels.
ROWS = [
    ("fault_unaware", r"Fault-unaware ($\varphi{=}0$) planner"),
    ("mmi", r"MMI planner"),
    ("dedup_history", r"Discard every later report of a used source (incl.\ new ones)"),
    ("dedup_history_initial", r"Discard repeat reports in the initial history only"),
    ("forbid_repeat", r"Forbid future repeat calls of a used persistent source"),
    ("dedup_both", r"Discard initial repeats and forbid future repeats"),
]


def cell(v):
    m, lo, hi = v[0], v[1], v[2]
    return f"{m:.2f} [{lo:.2f}, {hi:.2f}]"


L = [r"\begin{tabular}{@{}lcccc@{}}", r"\toprule",
     r" & \multicolumn{2}{c}{Selected 140} & \multicolumn{2}{c}{Full grid, 432} \\",
     r"\cmidrule(lr){2-3}\cmidrule(lr){4-5}",
     r"Policy & one-step & closed loop & one-step & closed loop \\", r"\midrule"]
for k, lab in ROWS:
    s, g = J["selected"][k], J["grid"][k]
    L.append(lab + " & " + " & ".join([cell(s["regret_1step"]), cell(s["regret_closed"]),
                                       cell(g["regret_1step"]), cell(g["regret_closed"])]) + r" \\")
L += [r"\bottomrule", r"\end{tabular}"]

with open(os.path.join(OUT, "bench_reference.tex"), "w", encoding="utf-8") as fh:
    fh.write("% generated by scripts/make_bench_table.py from raea4/bench/results/reference_policies.json; do not edit\n")
    fh.write("\n".join(L) + "\n")
print("wrote bench_reference")
