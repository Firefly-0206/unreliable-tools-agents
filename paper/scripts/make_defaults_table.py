"""Default-filling and fallback accounting for the written observation models (CORE, n=100 per cell)
-> tables/agent_k2defaults.tex, tables/nums_agent_defaults.tex.

Recovery rate (paper definition): mean of score_recovery(...)['struct_exact'] over ALL episodes of the cell, with no exclusion;
a full-fallback episode is scored from its default spec.  This script reports, per cell, how many episodes were
(a) full fallback (no usable JSON after two attempts), (b) completed by documented defaults without fallback, split into
key-field defaults (shared_fault / phi / persistent / group membership) and stale_emission-only defaults,
and the structure-exact rate excluding fallback episodes.

Reads (read only): raea4/agentenv/logs/{codex_terra_medium_k2decomp,ds_chat_fc_k2decomp}.jsonl, episodes.jsonl.
    python paper/scripts/make_defaults_table.py
"""
import json
import os
import sys

import numpy as np

AG = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))), "raea4", "agentenv")
sys.dont_write_bytecode = True
sys.path.insert(0, AG)
from env import load_episodes, CORE          # noqa: E402
import k2decomp as K2D                        # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "tables")
MODELS = [("Terra", "gpt-6.1-terra", "codex_terra_medium_k2decomp.jsonl"),
          ("Flash", "flash (non-thinking)", "ds_chat_fc_k2decomp.jsonl")]
CONDS = [("K1e", "KOneE"), ("K2e", "KTwoE"), ("K2p", "KTwoP")]
EMISSION = ".stale_emission"
KEY = (".shared_fault", ".phi", ".persistent")

eps = load_episodes()
mac, rows_tex = [], []
for tag, disp, fn in MODELS:
    recs = {}
    for line in open(os.path.join(AG, "logs", fn), encoding="utf-8"):
        r = json.loads(line)
        if r["status"].startswith("api_error") or not r.get("elicit"):
            continue
        recs[(r["episode"], r["condition"])] = r            # later successful rerun replaces earlier row
    first = True
    for cond, ck in CONDS:
        sel = [r for (e, c), r in recs.items() if c == cond and r["family"] in CORE]
        n = len(sel)
        assert n == 100, (tag, cond, n)
        fb = [r for r in sel if r["elicit"]["spec"]["fallback"]]
        nf = [r for r in sel if not r["elicit"]["spec"]["fallback"]]
        dflt = [r for r in nf if r["elicit"]["spec"]["defaults"]]
        key = [r for r in dflt if any(EMISSION not in str(d) and "clip" not in str(d) for d in r["elicit"]["spec"]["defaults"])]
        emi = [r for r in dflt if r not in key]
        se = lambda rs: [K2D.score_recovery(eps[r["episode"]], r["elicit"]["spec"])["struct_exact"] for r in rs]
        s_all, s_nf = 100 * np.mean(se(sel)), 100 * np.mean(se(nf))
        s_fb = se(fb)
        vals = dict(NFallback=len(fb), NDefaultsKey=len(key), NDefaultsEmission=len(emi), StructAll=f"{s_all:.0f}",
                    StructNoFallback=f"{s_nf:.0f}", StructFallbackOk=int(sum(s_fb)))
        for k, v in vals.items():
            mac.append(f"\\providecommand{{\\ag{tag}Def{ck}{k}}}{{{v}}}% src: logs/{fn} elicit.spec (fallback, defaults), CORE n=100; struct_exact = K2D.score_recovery")
        rows_tex.append(f"{disp if first else ''} & {cond} & {len(fb)} & {len(emi)} & {len(key)} & {s_all:.0f} & {s_nf:.0f} & {int(sum(s_fb))}/{len(fb)} \\\\")
        first = False
        print(tag, cond, vals, sorted({d for r in dflt for d in r["elicit"]["spec"]["defaults"]})[:12])
    rows_tex.append(r"\midrule")
rows_tex = rows_tex[:-1]
hdr = ("% generated by scripts/make_defaults_table.py from raea4/agentenv/logs/*_k2decomp.jsonl (elicit.spec.fallback, .defaults) and "
       "k2decomp.score_recovery; CORE n=100 per row; do not edit\n"
       "\\begin{tabular}{@{}llrrrrrr@{}}\n\\toprule\n"
       "Model & Cond. & full fallback & emission default only & key-field defaults & struct.\\ \\% (all) & struct.\\ \\% (no fallback) & exact among fallback \\\\\n\\midrule\n")
for tag, fn in (("Terra", "codex_terra_k2e_replay.jsonl"), ("Flash", "ds_chat_fc_k2e_replay.jsonl")):
    rr = [json.loads(l) for l in open(os.path.join(AG, "logs", fn), encoding="utf-8")]
    rr = [r for r in rr if r["family"] in CORE]
    assert len(rr) == 100
    mac.append(f"\\providecommand{{\\ag{tag}KTwoRSameSeqCore}}{{{sum(r['replay']['same_call_sequence'] for r in rr)}}}% src: logs/{fn} replay.same_call_sequence, CORE")
open(os.path.join(OUT, "agent_k2defaults.tex"), "w", encoding="utf-8").write(hdr + "\n".join(rows_tex) + "\n\\bottomrule\n\\end{tabular}\n")
open(os.path.join(OUT, "nums_agent_defaults.tex"), "w", encoding="utf-8").write("% generated by scripts/make_defaults_table.py; do not edit\n" + "\n".join(mac) + "\n")
