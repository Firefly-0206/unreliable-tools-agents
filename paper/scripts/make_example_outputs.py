"""Macros for the page-1 worked example (Figure 1): one held-out episode, scored exactly. No model call.
Episode: Sonnet 5.5, K2e, held-out confirmation log (raea4/agentenv/logs/confirm_claude_s55_k2e.jsonl), and its K2r replay
on the stored JSON (confirm_claude_s55_k2e_replay.jsonl). Scored with oracle.score_trajectory, as in anatomy_confirm.py.
Selection (post hoc, for illustration): held-out terra/Sonnet episodes with a parsed JSON, zero verdict advantage and the
largest step a non-replica probe where the oracle would probe a replica tool; this one has all regret in one step, a JSON
equal to the documented parameters, a correct verdict and two steps.
Writes tables/nums_example.tex.

    .venv/Scripts/python.exe paper/scripts/make_example_outputs.py
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
AG = os.path.normpath(os.path.join(HERE, "..", "..", "raea4", "agentenv"))
sys.path.insert(0, AG); os.chdir(AG)
from env import load_episodes, load_truth, srcmap  # noqa: E402
from oracle import true_model, qvalues, score_trajectory  # noqa: E402
from anatomy_confirm import load  # noqa: E402

EP = "SHARED-046"
eps, truth = load_episodes(), load_truth(); ep = eps[EP]
E = load("confirm_claude_s55_k2e.jsonl", "K2e", 25, 50)[EP]; R = load("confirm_claude_s55_k2e_replay.jsonl", "K2r", 25, 50)[EP]
s = score_trajectory(ep, E["log"], truth[EP]); r = score_trajectory(ep, R["log"], truth[EP])
js = json.loads(E["elicit"]["raw"])["observation_model"]; p = ep["params"]
grp = js["tool_groups"][0]; acc = js["accuracy"]
assert abs(grp["phi"] - p["phi"]) < 1e-9 and grp["shared_fault"] and grp["persistent"]
assert [round(acc[t], 2) for t in acc] == [round(t["q"], 2) for t in p["tools"]]
st = s["steps"][0]; assert st["action"] == ["probe", 2] and st["oracle"] == ["probe", 0]
assert abs(s["steps"][-1]["adv_verdict"]) < 1e-12 and s["correct"] and r["correct"] and r["regret"] < 1e-9
M = true_model(ep); q = qvalues(M, M.prior.copy(), float(M.budget))

BS = chr(92); mac = ["% generated by scripts/make_example_outputs.py (episode " + EP + ", Sonnet 5.5 held-out K2e and K2r); do not edit"]
def Mc(n, v, src): mac.append(f"{BS}providecommand{{{BS}{n}}}{{{v}}}% src: {src}")
Mc("exPhi", f"{grp['phi']:.2f}", "elicited JSON tool_groups[0].phi (= documented)")
for k, t in zip(["exAccStatus", "exAccDash", "exAccLog", "exAccLive"], acc): Mc(k, f"{acc[t]:.2f}", f"elicited JSON accuracy.{t}")
Mc("exCostLog", str(p["tools"][2]["cost"]), "params.tools[2].cost"); Mc("exCostStatus", str(p["tools"][0]["cost"]), "params.tools[0].cost")
Mc("exBudget", str(int(M.budget)), "params budget")
Mc("exQModel", f"{st['Q']:.2f}", "score_trajectory K2e steps[0].Q"); Mc("exV", f"{st['V']:.2f}", "steps[0].V")
Mc("exAdv", f"{st['adv']:.2f}", "steps[0].adv (= episode regret)"); Mc("exRegret", f"{s['regret']:.2f}", "K2e regret")
Mc("exShare", f"{100 * s['regret'] / s['V0']:.0f}", "K2e regret / V0 (%)")
Mc("exQLive", f"{q[('probe', 3)] - st['V']:.2f}", "root advantage of the live probe")
open(os.path.join(HERE, "..", "tables", "nums_example.tex"), "w", encoding="utf-8", newline="\n").write("\n".join(mac) + "\n")
print("\n".join(mac)); print("K2e log", E["log"]); print("K2r log", R["log"])
