"""Macros and appendix tables of the hard-description experiment (raea4/agentenv/PLAN_hd_hard_description.md).
Sources: raea4/agentenv/results/hd_analysis.json (hd_analysis.py), results/hd_bayes.json (hd_bayes.py), episodes_hd.jsonl.
Writes tables/nums_hd.tex, tables/agent_hd.tex (contrasts), tables/agent_hd_words.tex (how the words were read)."""
import json, os
import numpy as np
HERE = os.path.dirname(os.path.abspath(__file__))
AG = os.path.join(HERE, "..", "..", "raea4", "agentenv")
d = json.load(open(os.path.join(AG, "results", "hd_analysis.json")))
bayes = json.load(open(os.path.join(AG, "results", "hd_bayes.json")))
eps = [json.loads(l) for l in open(os.path.join(AG, "episodes_hd.jsonl"), encoding="utf-8")]
RUNS = [("flash", "Flash", "flash"), ("terra", "Terra", "terra"), ("sonnet", "Sonnet", "Sonnet 5.5")]
ARM = {"HN": "N", "HQ": "Q", "HI": "I"}; ARMLAB = {"HN": "numbers (HN)", "HQ": "words (HQ)", "HI": "words, implicit (HI)"}
WORDS = ["rare", "occasional", "frequent"]; WCAP = {"rare": "Rare", "occasional": "Occ", "frequent": "Freq"}

def sgn(x, nd): return ("+" if round(x, nd) > 0 else "$-$" if round(x, nd) < 0 else "") + f"{abs(x):.{nd}f}"
def pts(c): return f"{sgn(100 * c['mean'], 0)} [{sgn(100 * c['lo'], 0)}, {sgn(100 * c['hi'], 0)}]"
def reg(c): return f"{sgn(c['mean'], 2)} [{sgn(c['lo'], 2)}, {sgn(c['hi'], 2)}]"
def pos(c): return f"{c['mean']:.2f} [{c['lo']:.2f}, {c['hi']:.2f}]"

out = ["% generated by scripts/make_hd_outputs.py; do not edit"]
def mac(name, val, src): out.append(f"\\providecommand{{\\hd{name}}}{{{val}}}% src: hd_analysis.json:{src}")

hq = [e for e in eps if e["arm"] == "HQ"]
mac("Draws", len(hq), "episodes_hd.jsonl")
for w in WORDS: mac(f"N{WCAP[w]}", sum(e["phi_word"] == w for e in hq), "episodes_hd.jsonl")
mac("OracleFirstLow", f"{100 * np.mean([e['oracle_first'] == ['probe', 0] for e in hq if e['phi_word'] != 'frequent']):.0f}", "episodes_hd.jsonl")
mac("BayesRegret", f"{np.mean([v['regret'] for v in bayes.values()]):.2f}", "hd_bayes.json")
mac("BayesFirst", f"{100 * np.mean([v['first'] for v in bayes.values()]):.0f}", "hd_bayes.json")
mac("OracleFirstAll", f"{100 * np.mean([e['oracle_first'] == ['probe', 0] for e in hq]):.0f}", "episodes_hd.jsonl")

rows, wrows = [], []
for key, M, label in RUNS:
    r = d[key]; C = r["contrasts"]; first = True
    for arm in r["arms"]:
        A = ARM[arm]; c0 = r["cells"][arm]; p = f"{M}{A}"
        aw = C[f"{arm} H3 first model-planner|low, as written"]; pw = C[f"{arm} H3 own-plan pass-over|low, as written"]
        mac(f"{p}Usable", c0["usable"], f"{key}.cells.{arm}.usable"); mac(f"{p}NTol", c0["n_tol"], f"{key}.cells.{arm}.n_tol")
        mac(f"{p}Planner", pos(C[f"{arm} H1 K2r regret"]), f"{key}.{arm} H1"); mac(f"{p}Regret", pos(C[f"{arm} K2e regret"]), f"{key}.{arm} K2e")
        mac(f"{p}Gap", reg(C[f"{arm} H2 K2r-K2e|all"]), f"{key}.{arm} H2 all")
        mac(f"{p}Own", pts(aw), f"{key}.{arm} H3 as written"); mac(f"{p}OwnN", aw["n_ep"], f"{key}.{arm} H3 as written n")
        mac(f"{p}Pass", f"{100 * pw['mean']:.0f}", f"{key}.{arm} H3 pass as written")
        mac(f"{p}Oracle", pts(C[f"{arm} first model-oracle|low"]), f"{key}.{arm} model-oracle low")
        mac(f"{p}Track", pts(C[f"{arm} H4 first rare-frequent (model)"]), f"{key}.{arm} H4 model")
        if arm != "HN":
            mac(f"{p}DiffPlanner", reg(C[f"{arm}-HN H1 K2r regret"]), f"{key}.{arm}-HN H1")
            mac(f"{p}DiffRegret", reg(C[f"{arm}-HN H5 K2e regret"]), f"{key}.{arm}-HN H5 K2e")
            mac(f"{p}DiffGap", reg(C[f"{arm}-HN H5 K2r-K2e"]), f"{key}.{arm}-HN H5 gap")
            mac(f"{p}DiffFirst", pts(C[f"{arm}-HN H5 first model|low"]), f"{key}.{arm}-HN H5 first model")
            mac(f"{p}DiffOwn", pts(C[f"{arm}-HN H5 first model-planner|low"]), f"{key}.{arm}-HN H5 first model-planner")
            mac(f"{p}Bayes", pts(C[f"{arm} first model-bayes|low"]), f"{key}.{arm} model-bayes low")
            for w in WORDS:
                cw = c0["words"][w]
                mac(f"{p}Phi{WCAP[w]}", f"{cw['phi_written']['mean']:.2f}", f"{key}.cells.{arm}.words.{w}.phi_written")
                mac(f"{p}PhiIn{WCAP[w]}", f"{100 * cw['phi_in_range']:.0f}", f"{key}.cells.{arm}.words.{w}.phi_in_range")
            aa = c0["acc_written"]
            for a, nm in (("highly reliable", "HR"), ("usually right", "UR"), ("noisy", "NO")):
                mac(f"{p}Acc{nm}", f"{aa[a]['mean']:.2f}", f"{key}.cells.{arm}.acc_written.{a}"); mac(f"{p}AccIn{nm}", f"{100 * aa[a]['in_range']:.0f}", f"{key}.cells.{arm}.acc_written.{a}.in_range")
            wrows.append(f"{label} & {ARMLAB[arm]} & " + " & ".join(f"{c0['words'][w]['phi_written']['mean']:.2f} ({100 * c0['words'][w]['phi_in_range']:.0f})" for w in WORDS)
                         + " & " + " & ".join(f"{aa[a]['mean']:.2f} ({100 * aa[a]['in_range']:.0f})" for a in ("highly reliable", "usually right", "noisy")) + f" & {c0['n_tol']}/50 \\\\")
        rows.append(f"{label if first else ''} & {ARMLAB[arm]} & {c0['usable']}/50 & {pos(C[f'{arm} H1 K2r regret'])} & {pos(C[f'{arm} K2e regret'])} & "
                    f"{reg(C[f'{arm} H2 K2r-K2e|all'])} & {pts(aw)} ({aw['n_ep']}) & {100 * pw['mean']:.0f} & {pts(C[f'{arm} first model-oracle|low'])} & "
                    f"{pts(C[f'{arm} H4 first rare-frequent (model)'])} \\\\")
        first = False
    rows.append("\\midrule")
T = os.path.join(HERE, "..", "tables")
open(os.path.join(T, "nums_hd.tex"), "w").write("\n".join(out) + "\n")
open(os.path.join(T, "agent_hd.tex"), "w").write("\n".join(
    ["% generated by scripts/make_hd_outputs.py from raea4/agentenv/results/hd_analysis.json; do not edit",
     "\\begin{tabular}{@{}lllllllrll@{}}", "\\toprule",
     " & & usable & H1: K2r & K2e & H2: K2r$-$K2e & \\multicolumn{2}{c}{H3, low rates, JSON as written} & model $-$ oracle & H4: first call \\\\",
     "\\cmidrule(lr){7-8}",
     "Run & documentation & JSON & regret & regret & all episodes & first: model $-$ planner ($n$) & pass-over (\\%) & first call, low & rare $-$ frequent \\\\", "\\midrule"]
    + rows[:-1] + ["\\bottomrule", "\\end{tabular}"]) + "\n")
open(os.path.join(T, "agent_hd_words.tex"), "w").write("\n".join(
    ["% generated by scripts/make_hd_outputs.py from raea4/agentenv/results/hd_analysis.json; do not edit",
     "\\begin{tabular}{@{}lllllllll@{}}", "\\toprule",
     " & & \\multicolumn{3}{c}{fault rate written (\\% in range)} & \\multicolumn{3}{c}{accuracy written (\\% in range)} & all in \\\\",
     "\\cmidrule(lr){3-5}\\cmidrule(lr){6-8}",
     "Run & documentation & rare & occasional & frequent & highly reliable & usually right & noisy & range \\\\", "\\midrule"]
    + wrows + ["\\bottomrule", "\\end{tabular}"]) + "\n")
print(f"{len(out) - 1} macros")
