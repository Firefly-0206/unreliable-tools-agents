"""Macros and appendix table for K2e vs same-JSON K2r on strict subsets (no parser completion; and within a per-parameter tolerance).
Source: raea4/agentenv/results/k2r_strict_subset.json (agentenv/k2r_strict_subset.py; offline, post hoc).
Writes tables/nums_k2rstrict.tex and tables/agent_k2strict.tex."""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "..", "raea4", "agentenv", "results", "k2r_strict_subset.json")
d = json.load(open(SRC))

def f2(x): return f"{x:.2f}"
def sg(x): x = round(x, 2) + 0.0; return ("+" if x > 0 else "$-$" if x < 0 else "") + f"{abs(x):.2f}"
def dci(m): return f"{sg(m['diff'])} [{sg(m['lo'])}, {sg(m['hi'])}]"

NAMES = [("flash", "Flash", "flash", "main"), ("terra", "Terra", "terra (medium)", "main"),
         ("terra_high", "TerraHigh", "terra (high)", "main"), ("sonnet", "Sonnet", "Sonnet 5.5", "main"),
         ("confirm_flash", "CfFlash", "flash", "held-out"), ("confirm_terra", "CfTerra", "terra (medium)", "held-out"),
         ("confirm_sonnet", "CfSonnet", "Sonnet 5.5", "held-out")]

out = ["% generated by scripts/make_k2r_strict_outputs.py; do not edit",
       "% src: raea4/agentenv/results/k2r_strict_subset.json"]
rows = []
for key, M, label, split in NAMES:
    r = d[key]; assert r["n"] == 100
    a, c = r["as_written"], r["as_written_correct"]
    # the main-text claim: on written-and-correct JSONs the planner has zero regret in every episode
    assert c["K2r_max"] == 0.0, (key, c["K2r_max"])
    vals = {"AsWrittenN": str(a["n"]), "AsWrittenDiffCI": dci(a["K2r_minus_K2e"]), "AsWrittenKTwoR": f2(a["K2r"]["mean"]),
            "CorrectN": str(c["n"]), "CorrectKTwoE": f2(c["K2e"]["mean"]), "CorrectDiffCI": dci(c["K2r_minus_K2e"])}
    for k, v in vals.items():
        out.append(f"\\providecommand{{\\agStr{M}{k}}}{{{v}}}")
    rows.append(f"{split} & {label} & {a['n']} & {f2(a['K2e']['mean'])} & {f2(a['K2r']['mean'])} & {dci(a['K2r_minus_K2e'])}"
                f" & {c['n']} & {f2(c['K2e']['mean'])} & {f2(c['K2r']['mean'])} & {dci(c['K2r_minus_K2e'])} \\\\")
out.append(f"\\providecommand{{\\agStrTol}}{{{d['flash']['tol']}}}")
open(os.path.join(HERE, "..", "tables", "nums_k2rstrict.tex"), "w").write("\n".join(out) + "\n")

tab = ["% generated by scripts/make_k2r_strict_outputs.py from raea4/agentenv/results/k2r_strict_subset.json; do not edit",
       "\\begin{tabular}{@{}llrrrlrrrl@{}}", "\\toprule",
       " & & \\multicolumn{4}{c}{JSON used as written} & \\multicolumn{4}{c}{as written, within tolerance} \\\\",
       "\\cmidrule(lr){3-6}\\cmidrule(l){7-10}",
       "Episodes & Run & $n$ & K2e & K2r & K2r$-$K2e & $n$ & K2e & K2r & K2r$-$K2e \\\\", "\\midrule"]
for i, row in enumerate(rows):
    if i == 4: tab.append("\\midrule")
    tab.append(row)
tab += ["\\bottomrule", "\\end{tabular}"]
open(os.path.join(HERE, "..", "tables", "agent_k2strict.tex"), "w").write("\n".join(tab) + "\n")
print("\n".join(out)); print("\n".join(tab))
