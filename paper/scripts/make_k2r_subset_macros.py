"""Macros for K2e vs same-JSON K2r on the CORE episodes whose written K2e JSON has the exact tool grouping.
Source: raea4/agentenv/results/k2r_struct_subset.json (agentenv/k2r_struct_subset.py). Writes tables/nums_k2rsub.tex."""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "..", "raea4", "agentenv", "results", "k2r_struct_subset.json")
d = json.load(open(SRC))

def f2(x): return f"{x:.2f}"
def f3(x): return f"{x:.3f}"
def sg(x): x = round(x, 2) + 0.0; return ("+" if x > 0 else "$-$" if x < 0 else "") + f"{abs(x):.2f}"
def ci(lo, hi): return f"[{sg(lo)}, {sg(hi)}]"

out = ["% generated by scripts/make_k2r_subset_macros.py", "% src: raea4/agentenv/results/k2r_struct_subset.json"]
for key, M in [("flash", "Flash"), ("terra", "Terra"), ("sonnet", "Sonnet"), ("terra_high", "TerraHigh")]:
    r = d[key]; s = r["written_struct_exact"]
    # consistency with the main-table cells (all 100 CORE episodes)
    assert r["n"] == 100 and r["all"]["n"] == 100
    vals = {
        "N": str(r["n"]), "Written": str(r["n_written"]), "StructWritten": str(r["n_struct_written"]),
        "StructInclFallback": str(r["n_struct_incl_fallback"]), "SubN": str(s["n"]),
        "SubKTwoE": f2(s["K2e"]["mean"]), "SubKTwoR": f3(s["K2r"]["mean"]),
        "SubDiff": sg(s["K2r_minus_K2e"]["diff"]),
        "SubDiffCI": f"{sg(s['K2r_minus_K2e']['diff'])} {ci(s['K2r_minus_K2e']['lo'], s['K2r_minus_K2e']['hi'])}",
    }
    for k, v in vals.items():
        out.append(f"\\providecommand{{\\agSub{M}{k}}}{{{v}}}")
open(os.path.join(HERE, "..", "tables", "nums_k2rsub.tex"), "w").write("\n".join(out) + "\n")
print("\n".join(out))
