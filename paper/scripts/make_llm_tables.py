def cell2(J, key, c):
    if f"{key}|{c}" not in J["conditions"]:
        return "--", "--"
    r = cond(J, key, c)
    return f2(r["regret"][0]), pct(r["cbwa"])


def trip(J, key, c):
    cs = [cell2(J, key, f"{c}{k}") for k in (1, 2, 3)]
    return " / ".join(x[0] for x in cs), " / ".join(x[1] for x in cs)


