def minus(s):
    s = s.replace("-0.00", "0.00")          # no negative zeros
    return s.replace("-", "$-$")


def f2(x):
    return minus(f"{x:.2f}")


def ci(v, d=2):
    return minus(f"{v[0]:.{d}f} [{v[1]:.{d}f}, {v[2]:.{d}f}]")


def pct(v):
    return f"{100 * v[0]:.0f}"


def pcti(v):
    return minus(f"{100 * v[0]:.0f} [{100 * v[1]:.0f}, {100 * v[2]:.0f}]")


def cond(J, key, c):
    return J["conditions"][f"{key}|{c}"]


def contr(J, key, name):
    return J["contrasts"][f"{key}|{name}"]


def write(name, src, body):
    with open(os.path.join(OUT, name), "w", encoding="utf-8") as fh:
        fh.write(HDR.replace("%s", src) + body)
    print("wrote", name)


