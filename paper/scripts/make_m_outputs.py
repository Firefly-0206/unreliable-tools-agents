"""Macros and appendix tables of the difficulty-matched fault / fault-free experiment (raea4/agentenv/PLAN_m_matched.md).
Source: raea4/agentenv/results/m_analysis.json (m_analysis.py) and raea4/agentenv/m_matching.json (make_episodes_m.py).
Writes tables/nums_m.tex, agent_m_cells.tex, agent_m_contrasts.tex.

    python paper/scripts/make_m_outputs.py
"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
AG = os.path.join(HERE, "..", "..", "raea4", "agentenv")
A = json.load(open(os.path.join(AG, "results", "m_analysis.json"), encoding="utf-8"))
MM = json.load(open(os.path.join(AG, "m_matching.json"), encoding="utf-8"))["summary"]
RUNS = [(k, t, l) for k, t, l in [("flash", "Flash", "flash"), ("terra", "Terra", "terra"), ("sonnet", "Sonnet", "Sonnet 5.5")] if k in A]
T = os.path.join(HERE, "..", "tables"); NL, BS, MINUS = chr(10), chr(92), "$-$"


def num(x, d=2):
    s = f"{abs(x):.{d}f}"
    return s if float(s) == 0 else (MINUS if x < 0 else "") + s


def ci(c, d=2, k=1.0):
    return f"{num(k * c['mean'], d)} [{num(k * c['lo'], d)}, {num(k * c['hi'], d)}]"


mac = ["% generated by scripts/make_m_outputs.py from raea4/agentenv/results/m_analysis.json and m_matching.json; do not edit"]
def M(name, val, src): mac.append(f"{BS}providecommand{{{BS}{name}}}{{{val}}}% src: {src}")
M("mmPairs", str(MM["n_pairs"]), "m_matching.json:summary.n_pairs"); M("mmDraws", str(MM["draws"]), "m_matching.json:summary.draws"); M("mmSkipped", str(MM["skipped"]), "m_matching.json:summary.skipped")
M("mmMarginF", f"{MM['margin_MF']:.2f}", "m_matching.json:summary.margin_MF"); M("mmMarginZ", f"{MM['margin_MZ']:.2f}", "m_matching.json:summary.margin_MZ")
M("mmMaxDiff", f"{MM['max_margin_diff']:.3f}", "m_matching.json:summary.max_margin_diff")
M("mmValueF", f"{MM['value_MF']:.2f}", "m_matching.json:summary.value_MF"); M("mmValueZ", f"{MM['value_MZ']:.2f}", "m_matching.json:summary.value_MZ")
M("mmMyopic", f"{100 * MM['myopic_ok']:.0f}", "m_matching.json:summary.myopic_ok (%)")
M("mmAccF", f"{MM['q_rep_MF']:.2f}", "m_matching.json:summary.q_rep_MF"); M("mmAccZ", f"{MM['q_rep_MZ']:.2f}", "m_matching.json:summary.q_rep_MZ")
cells, cons = [], []
CN = [("M1 subopt first MF-MZ", "SubDiff", "M1: suboptimal first action, MF$-$MZ (points)", 0, 100.0), ("M1 first-step loss MF-MZ", "LossDiff", "M1: first-step loss, MF$-$MZ", 2, 1.0),
      ("M2 regret MF-MZ", "RegDiff", "M2: regret, MF$-$MZ", 2, 1.0), ("M2 under MF-MZ", "UnderDiff", "M2: under-use regret of tool 0, MF$-$MZ", 2, 1.0),
      ("M3 K2r-K2e|MF", "GapF", "M3: K2r$-$K2e, MF", 2, 1.0), ("M3 K2r-K2e|MZ", "GapZ", "M3: K2r$-$K2e, MZ", 2, 1.0),
      ("M4 subopt first MF-MZ|both within tolerance", "SubDiffTol", "M4: as M1, both JSONs within tolerance (points)", 0, 100.0)]
for k, tag, lab in RUNS:
    o = A[k]
    M(f"mm{tag}PairsTol", str(o["pairs_tol"]), f"m_analysis.json:{k}.pairs_tol")
    for arm, an in (("MF", "F"), ("MZ", "Z")):
        c = o["cells"][arm]
        M(f"mm{tag}Sub{an}", f"{100 * c['subopt']['mean']:.0f}", f"m_analysis.json:{k}.cells.{arm}.subopt (%)")
        M(f"mm{tag}SubCI{an}", ci(c["subopt"], 0, 100), f"m_analysis.json:{k}.cells.{arm}.subopt (%)")
        M(f"mm{tag}First{an}", f"{100 * c['first_model']['mean']:.0f}", f"m_analysis.json:{k}.cells.{arm}.first_model (%)")
        M(f"mm{tag}Reg{an}", f"{c['regret']['mean']:.2f}", f"m_analysis.json:{k}.cells.{arm}.regret")
        M(f"mm{tag}KTwoR{an}", f"{c['K2r']['mean']:.2f}", f"m_analysis.json:{k}.cells.{arm}.K2r")
        cells.append(f"{lab if arm == 'MF' else ''} & {arm} & {100 * c['first_model']['mean']:.0f} & {100 * c['first_planner']:.0f} & {ci(c['subopt'], 0, 100)} & {c['loss1']['mean']:.2f} & "
                     f"{c['regret']['mean']:.2f} & {c['K2r']['mean']:.2f} & {c['under']['mean']:.2f} & {c['verdict']['mean']:.2f} & {c['calls']['mean']:.1f} & {100 * c['tol']:.0f} {BS}{BS}")
    for key, nm, _, d, s in CN:
        if key in o["contrasts"]: M(f"mm{tag}{nm}", ci(o["contrasts"][key], d, s), f"m_analysis.json:{k}.contrasts[{key}]")
for key, nm, lab, d, s in CN:
    cons.append(lab + " & " + " & ".join(ci(A[k]["contrasts"][key], d, s) if key in A[k]["contrasts"] else "--" for k, _, _ in RUNS) + f" {BS}{BS}")
W = lambda fn, lines: open(os.path.join(T, fn), "w", encoding="utf-8", newline="\n").write(NL.join(lines) + NL)
W("agent_m_cells.tex", ["% generated by scripts/make_m_outputs.py from raea4/agentenv/results/m_analysis.json; do not edit",
                        r"\begin{tabular}{@{}llrrcrrrrrrr@{}}", r"\toprule",
                        r"Run & arm & first & planner & suboptimal first (\%) & loss$_1$ & K2e & K2r & under & verdict & calls & tol.\ (\%) \\", r"\midrule"] + cells + [r"\bottomrule", r"\end{tabular}"])
W("agent_m_contrasts.tex", ["% generated by scripts/make_m_outputs.py from raea4/agentenv/results/m_analysis.json; do not edit",
                            r"\begin{tabular}{@{}l" + "c" * len(RUNS) + "@{}}", r"\toprule", "Contrast & " + " & ".join(l for _, _, l in RUNS) + f" {BS}{BS}", r"\midrule"] + cons + [r"\bottomrule", r"\end{tabular}"])
W("nums_m.tex", mac)
print(len(mac) - 1, "macros")
