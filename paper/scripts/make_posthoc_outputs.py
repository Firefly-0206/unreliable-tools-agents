"""Macros and appendix tables of three post hoc analyses that need no model call:
  raea4/agentenv/results/k2d_summary.json          (k2d_summary.py: decision-value planner with independent checks on the model's JSON)
  raea4/agentenv/results/difficulty_matched.json   (difficulty_matched.py: first decisions matched on the exact value margin)
  raea4/agentenv/results/scenario_sensitivity.json (scenario_sensitivity.py: per-scenario, leave-one-scenario-out, multiplicity)
Writes tables/nums_posthoc.tex, agent_k2d.tex, agent_dm.tex, agent_sens.tex.

    python paper/scripts/make_posthoc_outputs.py
"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "..", "..", "raea4", "agentenv", "results")
T = os.path.join(HERE, "..", "tables")
J = lambda f: json.load(open(os.path.join(RES, f), encoding="utf-8"))
NL, BS = chr(10), chr(92)
MINUS = "$-$"


def num(x, d=2, sign=False):
    s = f"{abs(x):.{d}f}"
    if float(s) == 0: return s
    return (MINUS if x < 0 else ("+" if sign else "")) + s


def ci(m, lo, hi, d=2, k=1.0):
    return f"{num(k * m, d)} [{num(k * lo, d)}, {num(k * hi, d)}]"


K2 = J("k2d_summary.json"); DM = J("difficulty_matched.json"); SE = J("scenario_sensitivity.json")
RUNS4 = [("flash", "Flash", "flash"), ("terra", "Terra", "terra (medium)"), ("terra_high", "TerraHigh", "terra (high)"), ("sonnet", "Sonnet", "Sonnet 5.5 (high)")]
RUNS3 = [r for r in RUNS4 if r[0] != "terra_high"]
mac = ["% generated by scripts/make_posthoc_outputs.py; do not edit"]
def M(name, val, src): mac.append(f"{BS}providecommand{{{BS}{name}}}{{{val}}}% src: {src}")

# ---- K2d
rows = []
for k, tag, lab in RUNS4:
    m = K2[k]
    for c, cn in (("K2d", "KTwoD"), ("K2dp", "KTwoDP")):
        M(f"kd{tag}{cn}", num(m[c]["mean"]), f"k2d_summary.json:{k}.{c}.mean")
    for c, cn in (("K2d-K2e", "KTwoDmKTwoE"), ("K2dp-K2e", "KTwoDPmKTwoE"), ("K2r-K2d", "KTwoRmKTwoD"), ("K2r-K2dp", "KTwoRmKTwoDP")):
        M(f"kd{tag}{cn}", ci(m[c]["diff"], m[c]["lo"], m[c]["hi"]), f"k2d_summary.json:{k}.{c}")
    rows.append(f"{lab} & {num(m['K2e']['mean'])} & {num(m['K2v']['mean'])} & {num(m['K2d']['mean'])} & {num(m['K2dp']['mean'])} & {num(m['K2r']['mean'])} & "
                f"{ci(m['K2d-K2e']['diff'], m['K2d-K2e']['lo'], m['K2d-K2e']['hi'])} & {ci(m['K2r-K2dp']['diff'], m['K2r-K2dp']['lo'], m['K2r-K2dp']['hi'])} {BS}{BS}")
open(os.path.join(T, "agent_k2d.tex"), "w", encoding="utf-8", newline="\n").write(NL.join(
    ["% generated by scripts/make_posthoc_outputs.py from raea4/agentenv/results/k2d_summary.json; do not edit",
     r"\begin{tabular}{@{}lrrrrrrr@{}}", r"\toprule",
     r"Run & K2e & K2v & K2d & K2dp & K2r & K2d$-$K2e & K2r$-$K2dp \\", r"\midrule"] + rows + [r"\bottomrule", r"\end{tabular}"]) + NL)

# ---- difficulty-matched first decisions
rows = []
for k, tag, lab in RUNS3:
    d = DM[k]; m, c = d["matched"], d["ci"]
    M(f"dm{tag}Diff", ci(m["subopt"], c["subopt"][0], c["subopt"][1], 0, 100), f"difficulty_matched.json:{k}.matched.subopt (points)")
    M(f"dm{tag}R", f"{100 * m['Rsubopt']:.0f}", f"difficulty_matched.json:{k}.matched.Rsubopt (%)")
    M(f"dm{tag}N", f"{100 * m['Nsubopt']:.0f}", f"difficulty_matched.json:{k}.matched.Nsubopt (%)")
    M(f"dm{tag}LossDiff", ci(m["loss"], c["loss"][0], c["loss"][1]), f"difficulty_matched.json:{k}.matched.loss")
    rows.append(f"{lab.replace(' (medium)', '').replace(' (high)', '')} & {100 * d['raw']['R']['subopt']:.0f} / {100 * d['raw']['N']['subopt']:.0f} & {100 * m['Rsubopt']:.0f} / {100 * m['Nsubopt']:.0f} & "
                f"{ci(m['subopt'], c['subopt'][0], c['subopt'][1], 0, 100)} & {num(m['Rloss'])} / {num(m['Nloss'])} & {ci(m['loss'], c['loss'][0], c['loss'][1])} {BS}{BS}")
d0 = DM["terra"]
M("dmNR", str(d0["raw"]["R"]["n"]), "difficulty_matched.json:terra.raw.R.n"); M("dmNN", str(d0["raw"]["N"]["n"]), "difficulty_matched.json:terra.raw.N.n")
M("dmMarginR", num(d0["raw"]["R"]["margin"]), "difficulty_matched.json:terra.raw.R.margin (median)"); M("dmMarginN", num(d0["raw"]["N"]["margin"]), "difficulty_matched.json:terra.raw.N.margin (median)")
M("dmWeight", f"{d0['matched']['weight']:.0f}", "difficulty_matched.json:terra.matched.weight")
open(os.path.join(T, "agent_dm.tex"), "w", encoding="utf-8", newline="\n").write(NL.join(
    ["% generated by scripts/make_posthoc_outputs.py from raea4/agentenv/results/difficulty_matched.json; do not edit",
     r"\begin{tabular}{@{}lccccc@{}}", r"\toprule",
     r" & unmatched & \multicolumn{2}{c}{suboptimal first action (\%), matched} & \multicolumn{2}{c}{first-step loss, matched} \\",
     r"\cmidrule(lr){3-4}\cmidrule(l){5-6}",
     r"Run & R / N (\%) & R / N & R$-$N (points) & R / N & R$-$N \\", r"\midrule"] + rows + [r"\bottomrule", r"\end{tabular}"]) + NL)

# ---- scenario sensitivity
NAMES = {"core_gap": "K2r$-$K2e, CORE", "confirm_gap": "K2r$-$K2e, held-out", "x_first": "first call, model$-$oracle", "d2_gap": "K2r$-$K2e, second domain",
         "d2_first": "first call, second domain",
         "d3_gap": "K2r$-$K2e, third domain", "d3_first": "first call, third domain"}
RL = {"flash": "flash", "terra": "terra", "terra_high": "terra (high)", "sonnet": "Sonnet"}
rows, last, n_ok, n_bonf, n_same = [], None, 0, 0, 0
for key, r in SE.items():
    p = key.split("|"); pct = "first" in p[0]; k = 100.0 if pct else 1.0; d = 0 if pct else 2
    if last and p[0] != last: rows.append(r"\addlinespace")
    last = p[0]
    lab = NAMES[p[0]] + (", persistent" if p[-1] == "XP" else ", independent" if p[-1] == "XI" else "")
    b = r["bonf"]
    rows.append(f"{lab} & {RL[p[1]]} & {ci(r['est'], r['lo'], r['hi'], d, k)} & {r['same_sign']}/{r['n_scenarios']} & {num(k * r['loso_min'], d)} to {num(k * r['loso_max'], d)} & "
                f"{'yes' if r['loso_all_excl0'] else 'no'} & [{num(k * b['lo'], d)}, {num(k * b['hi'], d)}] {BS}{BS}")
    n_ok += r["loso_all_excl0"]; n_bonf += b["excl0"]; n_same += r["same_sign"] == r["n_scenarios"]
any_r = next(iter(SE.values()))
M("seN", str(len(SE)), "scenario_sensitivity.json: comparisons present"); M("seLosoOk", str(n_ok), "scenario_sensitivity.json: comparisons whose six leave-one-out intervals all exclude 0")
M("seBonfOk", str(n_bonf), "scenario_sensitivity.json: comparisons whose Bonferroni interval excludes 0"); M("seSameSign", str(n_same), "scenario_sensitivity.json: comparisons with the same sign in all scenarios")
M("seBonfLevel", f"{any_r['bonf']['level']:.2f}", "scenario_sensitivity.json: bonf.level (%)")
open(os.path.join(T, "agent_sens.tex"), "w", encoding="utf-8", newline="\n").write(NL.join(
    ["% generated by scripts/make_posthoc_outputs.py from raea4/agentenv/results/scenario_sensitivity.json; do not edit",
     r"\begin{tabular}{@{}llccccc@{}}", r"\toprule",
     r"Comparison & Run & estimate [95\%] & same sign & leave-one-out range & all excl.\ 0 & Bonferroni interval \\", r"\midrule"] + rows + [r"\bottomrule", r"\end{tabular}"]) + NL)
open(os.path.join(T, "nums_posthoc.tex"), "w", encoding="utf-8", newline="\n").write(NL.join(mac) + NL)
print(len(mac) - 1, "macros;", len(SE), "sensitivity rows")
