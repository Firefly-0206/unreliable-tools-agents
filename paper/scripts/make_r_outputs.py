"""Macros and appendix tables of the runbook case study (raea4/agentenv/PLAN_r_runbook.md).
Source: raea4/agentenv/results/r_analysis.json (r_analysis.py). Writes tables/nums_r.tex, agent_r_cells.tex, agent_r_contrasts.tex."""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "..", "raea4", "agentenv", "results", "r_analysis.json")
d = json.load(open(SRC))
RUNS = [("flash", "Flash", "flash"), ("terra", "Terra", "terra"), ("sonnet", "Sonnet", "Sonnet 5.5")]

def sgn(x, nd): return ("+" if round(x, nd) > 0 else "$-$" if round(x, nd) < 0 else "") + f"{abs(x):.{nd}f}"
def pts(c): return f"{sgn(100 * c['mean'], 0)} [{sgn(100 * c['lo'], 0)}, {sgn(100 * c['hi'], 0)}]"
def reg(c): return f"{sgn(c['mean'], 2)} [{sgn(c['lo'], 2)}, {sgn(c['hi'], 2)}]"
def pos(c): return f"{c['mean']:.2f} [{c['lo']:.2f}, {c['hi']:.2f}]"

out = ["% generated by scripts/make_r_outputs.py; do not edit"]
def mac(name, val, src): out.append(f"\\providecommand{{\\rb{name}}}{{{val}}}% src: r_analysis.json:{src}")

cells, cons = [], []
for key, M, label in RUNS:
    r = d[key]; C = r["contrasts"]; assert r["n"] == 75
    mac(f"{M}Usable", r["usable"], f"{key}.usable"); mac(f"{M}NTol", r["n_tol"], f"{key}.n_tol"); mac(f"{M}NoSubmit", r["no_submit"], f"{key}.no_submit")
    mac(f"{M}Invalid", r["invalid"], f"{key}.invalid"); mac(f"{M}OrigNTol", r["original"]["n_tol"], f"{key}.original.n_tol")
    mac(f"{M}Gap", reg(C["R1 K2r-K2e|all"]), f"{key}.R1 all")
    mac(f"{M}GapTol", reg(C["R1 K2r-K2e|within tolerance"]) if "R1 K2r-K2e|within tolerance" in C else "--", f"{key}.R1 within tolerance")
    mac(f"{M}PlannerTol", f"{C['K2r|within tolerance']['mean']:.2f}" if "K2r|within tolerance" in C else "--", f"{key}.K2r within tolerance")
    mac(f"{M}Regret", pos(C["regret K2e|all"]), f"{key}.regret K2e"); mac(f"{M}Planner", pos(C["regret K2r|all"]), f"{key}.regret K2r")
    mac(f"{M}LowGap", pts(C["R2 first model-oracle|low"]), f"{key}.R2 first"); mac(f"{M}LowUnder", pos(C["R2 under|low"]), f"{key}.R2 under")
    mac(f"{M}Track", pts(C["R3 first 0.10-0.70"]), f"{key}.R3"); mac(f"{M}FirstHigh", f"{100 * C['first at 0.70']['mean']:.0f}", f"{key}.first at 0.70")
    mac(f"{M}SurfFirst", pts(C["R4 first runbook-original|low"]), f"{key}.R4 first"); mac(f"{M}SurfRegret", reg(C["R4 regret runbook-original|all"]), f"{key}.R4 regret")
    mac(f"{M}SurfUnder", reg(C["R4 under runbook-original|low"]), f"{key}.R4 under"); mac(f"{M}SurfTol", pts(C["R4 tol runbook-original|all"]), f"{key}.R4 tol")
    for i, p in enumerate(("0.10", "0.30", "0.70")):
        c = r["cells"][p]
        cells.append(f"{label if i == 0 else ''} & {p} & {100 * c['first_model']['mean']:.0f} & {100 * c['first_oracle']:.0f} & {100 * c['first_planner']:.0f} & "
                     f"{c['regret']['mean']:.2f} & {c['K2r']['mean']:.2f} & {c['under']['mean']:.2f} & {c['over']['mean']:.2f} & {c['verdict']['mean']:.2f} & "
                     f"{c['calls']['mean']:.2f} & {100 * c['tol']:.0f} \\\\")
    cells.append("\\midrule")
    cons.append(f"{label} & {r['n_tol']}/75 & {reg(C['R1 K2r-K2e|all'])} & " + (reg(C["R1 K2r-K2e|within tolerance"]) if "R1 K2r-K2e|within tolerance" in C else "--")
                + f" & {pts(C['R2 first model-oracle|low'])} & {pts(C['R3 first 0.10-0.70'])} & {pts(C['R4 first runbook-original|low'])} & {reg(C['R4 regret runbook-original|all'])} \\\\")
T = os.path.join(HERE, "..", "tables")
open(os.path.join(T, "nums_r.tex"), "w").write("\n".join(out) + "\n")
open(os.path.join(T, "agent_r_cells.tex"), "w").write("\n".join(
    ["% generated by scripts/make_r_outputs.py from raea4/agentenv/results/r_analysis.json; do not edit",
     "\\begin{tabular}{@{}llrrrrrrrrrr@{}}", "\\toprule",
     "Run & $\\varphi$ & first: model (\\%) & oracle (\\%) & planner (\\%) & K2e & K2r & under-use & over-use & verdict & calls & JSON within tol.\\ (\\%) \\\\", "\\midrule"]
    + cells[:-1] + ["\\bottomrule", "\\end{tabular}"]) + "\n")
open(os.path.join(T, "agent_r_contrasts.tex"), "w").write("\n".join(
    ["% generated by scripts/make_r_outputs.py from raea4/agentenv/results/r_analysis.json; do not edit",
     "\\begin{tabular}{@{}llllllll@{}}", "\\toprule",
     " & JSON within & \\multicolumn{2}{c}{R1: K2r$-$K2e} & R2: model $-$ oracle & R3: first call & \\multicolumn{2}{c}{R4: runbook $-$ original surface} \\\\",
     "\\cmidrule(lr){3-4}\\cmidrule(l){7-8}",
     "Run & tolerance & all episodes & within tolerance & first call, $\\varphi\\le0.3$ & 0.10 $-$ 0.70 & first call, $\\varphi\\le0.3$ & regret \\\\", "\\midrule"]
    + cons + ["\\bottomrule", "\\end{tabular}"]) + "\n")
print("\n".join(out))
