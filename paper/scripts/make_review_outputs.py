"""Macros and appendix tables of three post hoc analyses that need no model call:
  raea4/agentenv/results/k2_audit_readings.json   (k2_audit_readings.py: description loss of alternative readings of K2)
  raea4/agentenv/results/near_tie_sensitivity.json (near_tie_sensitivity.py: attribution with near ties removed)
  raea4/agentenv/results/d2_de_split.json          (d2_de_split.py: second domain, D and E by JSON structure)
Writes tables/nums_rev.tex, agent_k2audit.tex, agent_neartie.tex, agent_d2_de.tex.

    python paper/scripts/make_review_outputs.py
"""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "..", "..", "raea4", "agentenv", "results")
T = os.path.join(HERE, "..", "tables")
J = lambda f: json.load(open(os.path.join(RES, f), encoding="utf-8"))
NL, BS = chr(10), chr(92)
MINUS = "$-$"


def num(x, d=2, sign=False):
    s = f"{abs(x):.{d}f}"
    if float(s) == 0: return s
    return (MINUS if x < 0 else ("+" if sign else "")) + s


def cis(c, d=2):
    if c.get("lo") is None: return num(c["mean"], d)
    return f"{num(c['mean'], d)} [{num(c['lo'], d)}, {num(c['hi'], d)}]"


mac = ["% generated by scripts/make_review_outputs.py; do not edit"]
def M(name, val, src): mac.append(f"{BS}providecommand{{{BS}{name}}}{{{val}}}% src: {src}")
def W(fn, lines): open(os.path.join(T, fn), "w", encoding="utf-8").write(NL.join(lines) + NL)

# ---- K2 audit: description loss of alternative readings
A = J("k2_audit_readings.json")["table"]
FAM = ["PERSIST", "SHARED", "MIXED", "TRANSIENT", "TRANSIENT_P"]
CORE = ["PERSIST", "SHARED", "MIXED", "TRANSIENT"]
core = lambda r: sum(A[f][r] for f in CORE) / len(CORE)
for r, tag in (("R1", "ROne"), ("R2", "RTwo"), ("R4", "RFour")):
    M(f"revAudit{tag}", num(core(r)), f"k2_audit_readings.json:table[CORE families][{r}] mean")
READ = [("R0", "true model (name equality = sharing)"), ("R1", "each tool has its own stale flag"),
        ("R2", "incidence per call, no persistence (MMI-DP)"), ("R3", "leftover stale mass on one other status"),
        ("R4", "incidence ignored (fault-unaware DP)"), ("R5", "true model, never repeat a cache call")]
L = [BS + "begin{tabular}{@{}llrrrrrr@{}}", BS + "toprule",
     " & Reading & PERSIST & SHARED & MIXED & TRANS. & TRANS." + BS + ",P & CORE " + BS + BS, BS + "midrule"]
for r, lab in READ:
    L.append(f"{r} & {lab} & " + " & ".join(num(max(A[f][r], 0.0)) for f in FAM) + f" & {num(max(core(r), 0.0))} " + BS + BS)
L += [BS + "bottomrule", BS + "end{tabular}"]
W("agent_k2audit.tex", L)

# ---- near ties
N = J("near_tie_sensitivity.json"); EPS = [0.0, 0.01, 0.02, 0.05, 0.1, 0.2]
for k, tag in (("terra", "Terra"), ("sonnet", "Sonnet")):
    h = N[f"{k}|held-out"]
    M(f"revNt{tag}Median", num(h["median_margin"]), f"near_tie_sensitivity.json:{k}|held-out.median_margin")
    M(f"revNt{tag}Small", f"{100 * h['share_steps_margin_lt_0.05']:.0f}", f"near_tie_sensitivity.json:{k}|held-out.share_steps_margin_lt_0.05")
drop = max(100 * (N[f"{k}|held-out"]["eps=0"]["share"] - N[f"{k}|held-out"]["eps=0.05"]["share"]) for k in ("terra", "sonnet"))
M("revNtMaxDrop", f"{drop:.0f}", "near_tie_sensitivity.json: max over terra/sonnet held-out of share(eps=0)-share(eps=0.05)")
L = [BS + "begin{tabular}{@{}ll" + "r" * len(EPS) + "l@{}}", BS + "toprule",
     "Run & Episodes & " + " & ".join(f"$" + BS + f"epsilon={e:g}$" for e in EPS) + " & C2 at $" + BS + "epsilon=0.05$ " + BS + BS, BS + "midrule"]
for k, lab in (("terra", "terra (medium)"), ("sonnet", "Sonnet 5.5 (high)")):
    for part in ("held-out", "original"):
        r = N[f"{k}|{part}"]; c = r["eps=0.05"]["pass_minus_rest"]
        L.append(f"{lab} & {part} & " + " & ".join(f"{100 * r[f'eps={e:g}']['share']:.0f}" for e in EPS)
                 + f" & {num(c['mean'])} [{num(c['lo'])}, {num(c['hi'])}] " + BS + BS)
L += [BS + "bottomrule", BS + "end{tabular}"]
W("agent_neartie.tex", L)

# ---- second domain: D and E by JSON structure
D = J("d2_de_split.json")
s = D["sonnet"]; n_all = s["all|all"]["n"]; n_wrong = s["all|struct_wrong"]["n"]
M("revDTwoSonnetWrongPct", f"{100 * n_wrong / n_all:.0f}", "d2_de_split.json:sonnet all|struct_wrong.n / all|all.n")
for js, tag in (("struct_wrong", "Wrong"), ("struct_ok", "Ok")):
    M(f"revDTwoSonnet{tag}D", cis(s[f"all|{js}"]["D"]), f"d2_de_split.json:sonnet.all|{js}.D")
    M(f"revDTwoSonnet{tag}E", cis(s[f"all|{js}"]["E"]), f"d2_de_split.json:sonnet.all|{js}.E")
L = [BS + "begin{tabular}{@{}llrrrr@{}}", BS + "toprule",
     "Run & JSON structure & $n$ & K2e regret & $D$ (K2r) & $E$ (K2e$-$K2r) " + BS + BS, BS + "midrule"]
for k, lab in (("flash", "flash (non-thinking)"), ("terra", "terra (medium)"), ("sonnet", "Sonnet 5.5 (high)")):
    if k not in D: continue
    for js, jl in (("all", "all"), ("struct_ok", "correct"), ("struct_wrong", "wrong")):
        x = D[k].get(f"all|{js}")
        if x: L.append(f"{lab} & {jl} & {x['n']} & {cis(x['K2e'])} & {cis(x['D'])} & {cis(x['E'])} " + BS + BS)
L += [BS + "bottomrule", BS + "end{tabular}"]
W("agent_d2_de.tex", L)

W("nums_rev.tex", mac)
print(NL.join(mac))
