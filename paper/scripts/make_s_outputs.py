"""Macros and appendix tables of the layered-supply experiment (raea4/agentenv/PLAN_s_supply.md).
Source: raea4/agentenv/results/s_analysis.json (s_analysis.py). Writes tables/nums_s.tex, agent_s_cells.tex, agent_s_contrasts.tex."""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "..", "raea4", "agentenv", "results", "s_analysis.json")
d = json.load(open(SRC))
RUNS = [("flash", "Flash", "flash"), ("terra", "Terra", "terra"), ("sonnet", "Sonnet", "Sonnet 5.5")]
CONDS = [("K1", "KOne", "K1: nothing added"), ("KC", "KC", "checklist, no numbers"), ("KS1", "KSOne", "+ exact posterior"),
         ("KS2", "KSTwo", "+ next-report probabilities"), ("KS2v", "KSTwoV", "+ one-step scores"), ("KS3", "KSThree", "KS2 + exact scores")]
PAIRS = [("KC", "K1", "KCmKOne"), ("KS1", "KC", "KSOnemKC"), ("KS2", "KS1", "KSTwomKSOne"), ("KS2v", "KS2", "KSTwoVmKSTwo"),
         ("KS3", "KS2v", "KSThreemKSTwoV"), ("KS3", "KS2", "KSThreemKSTwo"), ("KS3", "K1", "KSThreemKOne")]

def sgn(x, nd): return ("+" if round(x, nd) > 0 else "$-$" if round(x, nd) < 0 else "") + f"{abs(x):.{nd}f}"
def pts(c): return f"{sgn(100 * c['mean'], 0)} [{sgn(100 * c['lo'], 0)}, {sgn(100 * c['hi'], 0)}]"
def reg(c): return f"{sgn(c['mean'], 2)} [{sgn(c['lo'], 2)}, {sgn(c['hi'], 2)}]"
def pos(c): return f"{c['mean']:.2f} [{c['lo']:.2f}, {c['hi']:.2f}]"

out = ["% generated by scripts/make_s_outputs.py; do not edit"]
def mac(name, val, src): out.append(f"\\providecommand{{\\sp{name}}}{{{val}}}% src: s_analysis.json:{src}")

cells, cons = [], []
for key, M, label in RUNS:
    r = d[key]; C = r["contrasts"]; assert r["n"] == 50
    mac(f"{M}NoSubmit", sum(r["no_submit"].values()), f"{key}.no_submit"); mac(f"{M}Invalid", sum(r["invalid"].values()), f"{key}.invalid")
    for i, (c, cm, clab) in enumerate(CONDS):
        x = r["cells"][c]
        mac(f"{M}{cm}Regret", f"{x['regret']['mean']:.2f}", f"{key}.cells[{c}].regret"); mac(f"{M}{cm}RegretCI", pos(x["regret"]), f"{key}.cells[{c}].regret")
        mac(f"{M}{cm}First", f"{100 * x['first']['mean']:.0f}", f"{key}.cells[{c}].first")
        mac(f"{M}{cm}Gap", pts(C[f"G first model-oracle|{c}"]), f"{key}.G first model-oracle|{c}")
        mac(f"{M}{cm}Opt", f"{100 * x['opt_steps']['mean']:.0f}", f"{key}.cells[{c}].opt_steps")
        cells.append(f"{label if i == 0 else ''} & {clab} & {100 * x['first']['mean']:.0f} & {pts(C[f'G first model-oracle|{c}'])} & {pos(x['regret'])} & "
                     f"{x['under']['mean']:.2f} & {x['over']['mean']:.2f} & {x['verdict']['mean']:.2f} & {x['calls']['mean']:.2f} & {100 * x['opt_steps']['mean']:.0f} \\\\")
    cells.append("\\midrule")
    for a, b, nm in PAIRS:
        mac(f"{M}{nm}Regret", reg(C[f"L regret {a}-{b}"]), f"{key}.L regret {a}-{b}"); mac(f"{M}{nm}First", pts(C[f"L first {a}-{b}"]), f"{key}.L first {a}-{b}")
    cons.append(f"{label} & regret & " + " & ".join(reg(C[f"L regret {a}-{b}"]) for a, b, _ in PAIRS) + " \\\\")
    cons.append(f" & first call & " + " & ".join(pts(C[f"L first {a}-{b}"]) for a, b, _ in PAIRS) + " \\\\")
T = os.path.join(HERE, "..", "tables")
open(os.path.join(T, "nums_s.tex"), "w").write("\n".join(out) + "\n")
open(os.path.join(T, "agent_s_cells.tex"), "w").write("\n".join(
    ["% generated by scripts/make_s_outputs.py from raea4/agentenv/results/s_analysis.json; do not edit",
     "\\begin{tabular}{@{}lllllrrrrr@{}}", "\\toprule",
     "Run & Decision aid & first (\\%) & model $-$ oracle & regret & under-use & over-use & verdict & calls & optimal steps (\\%) \\\\", "\\midrule"]
    + cells[:-1] + ["\\bottomrule", "\\end{tabular}"]) + "\n")
open(os.path.join(T, "agent_s_contrasts.tex"), "w").write("\n".join(
    ["% generated by scripts/make_s_outputs.py from raea4/agentenv/results/s_analysis.json; do not edit",
     "\\begin{tabular}{@{}lllllllll@{}}", "\\toprule",
     "Run & & KC$-$K1 & KS1$-$KC & KS2$-$KS1 & KS2v$-$KS2 & KS3$-$KS2v & KS3$-$KS2 & KS3$-$K1 \\\\", "\\midrule"]
    + cons + ["\\bottomrule", "\\end{tabular}"]) + "\n")
print("\n".join(l for l in out if "Regret}" in l or "Gap}" in l))
