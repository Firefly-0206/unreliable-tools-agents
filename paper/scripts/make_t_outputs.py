"""Macros and appendix tables of the fault-wording experiment (raea4/agentenv/PLAN_t_wording.md).
Source: raea4/agentenv/results/t_analysis.json (t_analysis.py). Writes tables/nums_t.tex, agent_t_cells.tex, agent_t_contrasts.tex."""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "..", "raea4", "agentenv", "results", "t_analysis.json")
d = json.load(open(SRC))
RUNS = [("flash", "Flash", "flash"), ("terra", "Terra", "terra"), ("sonnet", "Sonnet", "Sonnet 5.5")]
ARMS = [("TS", "sentences"), ("TD", "probabilities, fresh / stale"), ("TT", "probabilities, one table")]

def sgn(x, nd): x = round(x, nd) + 0.0; return ("+" if x > 0 else "$-$" if x < 0 else "") + f"{abs(x):.{nd}f}"
def pts(c): return f"{sgn(100 * c['mean'], 0)} [{sgn(100 * c['lo'], 0)}, {sgn(100 * c['hi'], 0)}]"
def reg(c): return f"{sgn(c['mean'], 2)} [{sgn(c['lo'], 2)}, {sgn(c['hi'], 2)}]"
def pos(c): return f"{c['mean']:.2f} [{c['lo']:.2f}, {c['hi']:.2f}]"

out = ["% generated by scripts/make_t_outputs.py; do not edit"]
def mac(name, val, src): out.append(f"\\providecommand{{\\tw{name}}}{{{val}}}% src: t_analysis.json:{src}")

cells, cons = [], []
for key, M, label in RUNS:
    r = d[key]; C = r["contrasts"]; assert r["n"] == 150
    mac(f"{M}NoSubmit", r["no_submit"], f"{key}.no_submit")
    for arm, _ in ARMS:
        c = r["cells"][f"{arm}|all"]
        mac(f"{M}{arm}First", f"{100 * c['first_model']['mean']:.0f}", f"{key}.cells[{arm}|all].first_model")
        mac(f"{M}{arm}Gap", pts(C[f"T1 first model-oracle|{arm}"]), f"{key}.T1 first model-oracle|{arm}")
        mac(f"{M}{arm}Under", pos(C[f"T1 under|{arm}"]), f"{key}.T1 under|{arm}")
        mac(f"{M}{arm}Regret", f"{c['regret']['mean']:.2f}", f"{key}.cells[{arm}|all].regret")
    for tag, a, b, nm in [("T2", "TT", "TD", "TTmTD"), ("T3", "TD", "TS", "TDmTS"), ("T2+T3", "TT", "TS", "TTmTS")]:
        mac(f"{M}{nm}First", pts(C[f"{tag} first {a}-{b}"]), f"{key}.{tag} first {a}-{b}")
        mac(f"{M}{nm}Under", reg(C[f"{tag} under {a}-{b}"]), f"{key}.{tag} under {a}-{b}")
        mac(f"{M}{nm}Regret", reg(C[f"{tag} regret {a}-{b}"]), f"{key}.{tag} regret {a}-{b}")
    for i, (arm, alab) in enumerate(ARMS):
        for p in ("0.10", "0.30"):
            c = r["cells"][f"{arm}|{p}"]
            cells.append(f"{label if (i == 0 and p == '0.10') else ''} & {alab if p == '0.10' else ''} & {p} & {100 * c['first_model']['mean']:.0f} & "
                         f"{100 * c['first_oracle']:.0f} & {100 * c['used_model']:.0f} & {c['regret']['mean']:.2f} & {c['under']['mean']:.2f} & "
                         f"{c['over']['mean']:.2f} & {c['verdict']['mean']:.2f} & {c['calls']['mean']:.2f} \\\\")
    cells.append("\\midrule")
    cons.append(f"{label} & {pts(C['T1 first model-oracle|TS'])} & {pts(C['T1 first model-oracle|TD'])} & {pts(C['T1 first model-oracle|TT'])} & "
                f"{pts(C['T2 first TT-TD'])} & {reg(C['T2 under TT-TD'])} & {reg(C['T2 regret TT-TD'])} & {pts(C['T3 first TD-TS'])} \\\\")
mac("OracleFirstLow", f"{100 * d['terra']['cells']['TT|0.10']['first_oracle']:.0f}", "cells[TT|0.10].first_oracle")
mac("OracleFirstHigh", f"{100 * d['terra']['cells']['TT|0.30']['first_oracle']:.0f}", "cells[TT|0.30].first_oracle")
T = os.path.join(HERE, "..", "tables")
open(os.path.join(T, "nums_t.tex"), "w").write("\n".join(out) + "\n")
open(os.path.join(T, "agent_t_cells.tex"), "w").write("\n".join(
    ["% generated by scripts/make_t_outputs.py from raea4/agentenv/results/t_analysis.json; do not edit",
     "\\begin{tabular}{@{}lllrrrrrrrr@{}}", "\\toprule",
     "Run & Documentation & $\\varphi$ & first: model (\\%) & oracle (\\%) & used (\\%) & regret & under-use & over-use & verdict & calls \\\\", "\\midrule"]
    + cells[:-1] + ["\\bottomrule", "\\end{tabular}"]) + "\n")
open(os.path.join(T, "agent_t_contrasts.tex"), "w").write("\n".join(
    ["% generated by scripts/make_t_outputs.py from raea4/agentenv/results/t_analysis.json; do not edit",
     "\\begin{tabular}{@{}llllllll@{}}", "\\toprule",
     " & \\multicolumn{3}{c}{T1: model $-$ oracle first-call share} & \\multicolumn{3}{c}{T2: one table $-$ fresh / stale} & T3: fresh / stale $-$ sentences \\\\",
     "\\cmidrule(lr){2-4}\\cmidrule(lr){5-7}\\cmidrule(l){8-8}",
     "Run & sentences & fresh / stale & one table & first-call share & under-use regret & regret & first-call share \\\\", "\\midrule"]
    + cons + ["\\bottomrule", "\\end{tabular}"]) + "\n")
print("\n".join(out))
