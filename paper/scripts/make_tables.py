def chk_rate(key):
    e = CHK["exclusion"][key]
    return e["violated_inB"], e["condition_holds"]


def s_get(S, fam, cell, pol, field="regret"):
    return S[fam][cell]["policies"][pol][field]


def arrow(a, b):
    return f"{f2(a)}{ARROW}{f2(b)}"


