_cache = {}


def J(rel):
    if rel not in _cache:
        with open(R / rel, encoding="utf-8") as fh:
            _cache[rel] = json.load(fh)
    return _cache[rel]


# ----------------------------------------------------------------------------- formatting helpers
def sg(x, d=2):
    """Number with a typeset minus sign; negative zero prints as 0."""
    s = f"{abs(x):.{d}f}"
    return ("$-$" if x < 0 and float(s) != 0 else "") + s


def ci(m, lo, hi, d=2):
    return f"{sg(m, d)}\\,\\simci{{{sg(lo, d)}}}{{{sg(hi, d)}}}"


def ci_e(e, d=2, hide_zero=True):
    """mean regret with CI from an entry having regret/lo/hi; no CI for the exact reference (lo=hi=0)."""
    if hide_zero and e["lo"] == 0 and e["hi"] == 0:
        return sg(e["regret"], d)
    return ci(e["regret"], e["lo"], e["hi"], d)


def pct(x, d=1):
    return f"{100 * x:.{d}f}"


def f2(x):
    return sg(x, 2)


DASH = "--"
ARROW = "$\\to$"


def tabular(colspec, header_lines, body_lines):
    out = ["% generated by scripts/make_tables.py -- do not edit by hand",
           "\\begin{tabular}{" + colspec + "}", "\\toprule"]
    out += header_lines
    out += ["\\midrule"]
    out += body_lines
    out += ["\\bottomrule", "\\end{tabular}", ""]
    return "\n".join(out)


def write(name, text):
    (OUT / f"{name}.tex").write_text(text, encoding="utf-8")
    print("wrote", name)


def row(cells):
    return " & ".join(str(c) for c in cells) + " \\\\"


# ----------------------------------------------------------------------------- number macros
NUMS = []
_DIG = ["Zero", "One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight", "Nine"]
_names = set()


def mname(key):
    parts = re.split(r"[^A-Za-z0-9]+", key)
    out = "sn"
    for p in parts:
        if not p:
            continue
        for ch in p:
            out += _DIG[int(ch)] if ch.isdigit() else ch
        out = out[:3] + out[3:]
    # camelCase: capitalise first letter after each separator
    s = "sn"
    for p in parts:
        if not p:
            continue
        q = "".join(_DIG[int(ch)] if ch.isdigit() else ch for ch in p)
        s += q[0].upper() + q[1:]
    return s


def num(key, text, src):
    name = mname(key)
    assert name not in _names, f"duplicate macro {name}"
    _names.add(name)
    NUMS.append(f"\\providecommand{{\\{name}}}{{{text}}}% src: {src}")
    return name


