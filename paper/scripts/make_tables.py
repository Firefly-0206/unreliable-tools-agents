def main_row(label, vr, dr, vs, ds, ind, shared_dp=None, brk=False):
    """vr/vs: VOI-1 entries (or None); dr/ds: DP entries; ind: DP entry or None. SHARED diagnostics from ds."""
    c = [label,
         f2(vr["regret"]) if vr else DASH, ci_e(dr),
         f2(vs["regret"]) if vs else DASH, ci_e(ds),
         pct(ds["severe"], 1), pct(ds["esc"], 0), f2(ds["repeat"]),
         f2(ind["regret"]) if ind else DASH]
    return row(c)


