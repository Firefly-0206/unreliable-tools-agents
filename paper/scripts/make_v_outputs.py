"""tables/agent_v_cells.tex, tables/agent_v_contrasts.tex, tables/agent_v_kimi.tex, tables/nums_v.tex from
raea4/agentenv/results/v_analysis.json (v_analysis.py; plan PLAN_v_cost_style.md). No model call.

    python paper/scripts/make_v_outputs.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
A = json.load(open(os.path.join(os.path.dirname(ROOT), "raea4", "agentenv", "results", "v_analysis.json"), encoding="utf-8"))
RUNS = [(k, t, l) for k, t, l in [("flash", "Flash", "flash"), ("terra", "Terra", "terra (medium)"), ("sonnet", "Sonnet", "Sonnet 5.5 (high)")] if k in A and "V" in A[k]]
NL, BS, MINUS = chr(10), chr(92), "$-$"
CELLN = {"XP10": ("sentences, costs as drawn (X run), 0.10", "RefTen"), "XP30": ("sentences, costs as drawn (X run), 0.30", "RefThirty"),
         "VC2": ("replica cost 2, 0.10", "CostTwo"), "VC3": ("replica cost 3, 0.10", "CostThree"), "VL3": ("log cost 3, 0.30", "LogThree"),
         "VS10": ("field list, 0.10", "SpecTen"), "VS30": ("field list, 0.30", "SpecThirty"), "XP50": ("0.50", "Fifty"), "XP70": ("0.70", "Seventy")}
ORDER = ["XP10", "VC2", "VC3", "XP30", "VL3", "VS10", "VS30"]


def num(x, plus=False, nd=2):
    s = f"{abs(x):.{nd}f}"
    if float(s) == 0: return s
    return (MINUS if x < 0 else ("+" if plus else "")) + s
def ci(d, plus=False, k=1, nd=2): return f"{num(k * d['mean'], plus, nd)} [{num(k * d['lo'], plus, nd)}, {num(k * d['hi'], plus, nd)}]"
def pc(x): return f"{100 * x:.0f}"


mac = []
def M(name, val, src): mac.append(BS + "providecommand{" + BS + "vv" + name + "}{" + str(val) + "}% src: v_analysis.json:" + src)


def cell_macros(tag, key, part, cells):
    for cn, c in cells.items():
        n = CELLN[cn][1]
        M(f"{tag}{n}First", pc(c["first_rep"]["mean"]), f"{key}.{part}.cells[{cn}].first_rep"); M(f"{tag}{n}Oracle", pc(c["oracle_rep"]), f"{key}.{part}.cells[{cn}].oracle_rep")
        M(f"{tag}{n}Regret", num(c["regret"]["mean"]), f"{key}.{part}.cells[{cn}].regret"); M(f"{tag}{n}Planner", num(c["K2r"]["mean"]), f"{key}.{part}.cells[{cn}].K2r")
        M(f"{tag}{n}Log", pc(c["first_log"]), f"{key}.{part}.cells[{cn}].first_log"); M(f"{tag}{n}Verdict", num(c["verdict"]["mean"]), f"{key}.{part}.cells[{cn}].verdict")


def cell_row(lab, cn, c):
    return (f"{lab} & {CELLN[cn][0]} & {pc(c['first_rep']['mean'])} & {pc(c['oracle_rep'])} & {pc(c['planner_rep'])} & {pc(c['first_log'])} & {pc(c['first_other'])} & "
            f"{num(c['regret']['mean'])} & {num(c['K2r']['mean'])} & {num(c['under']['mean'])} & {num(c['over']['mean'])} & {num(c['verdict']['mean'])} & {num(c['calls']['mean'])} " + BS * 2)


CN = [("V1 first replica cost1-cost3|0.10", "CostTrack", 100), ("V1 first replica cost1-cost2|0.10", "CostTrackTwo", 100), ("V1 first replica model-oracle|VC2", "CostTwoGap", 100),
      ("V1 first replica model-oracle|VC3", "CostThreeGap", 100), ("V2 first replica logcost3-logcost1|0.30", "LogShift", 100), ("V2 first replica model-oracle|VL3", "LogGap", 100),
      ("V2 under|VL3", "LogUnder", 1), ("V3 first replica model-oracle|spec", "SpecGap", 100), ("V3 first replica spec-prose|0.10,0.30", "SpecShift", 100),
      ("V3 regret spec-prose|0.10,0.30", "SpecRegretDiff", 1), ("V3 K2r-K2e|spec", "SpecExec", 1), ("V3 under|spec", "SpecUnder", 1), ("V4 K2r-K2e|cost", "CostExec", 1),
      ("V4 first-action match, as-if minus oracle|cost", "AsifDiff", 100), ("V4 first-action match, as-if|cost", "AsifMatch", 100), ("V4 first-action match, oracle|cost", "OracleMatch", 100),
      ("first replica model-oracle|prose (X run)", "ProseGap", 100)]
rows, crow = [], []
for key, tag, lab in RUNS:
    o = A[key]["V"]; D = o["contrasts"]; M(tag + "Usable", o["usable"], f"{key}.V.usable"); M(tag + "NoSubmit", o["no_submit"], f"{key}.V.no_submit"); cell_macros(tag, key, "V", o["cells"])
    for i, cn in enumerate(c for c in ORDER if c in o["cells"]): rows.append(cell_row(lab if i == 0 else "", cn, o["cells"][cn]))
    rows.append(BS + "addlinespace")
    for name, mn, k in CN:
        if name in D: M(tag + mn, ci(D[name], k == 100 or "Exec" in mn or "Diff" in mn, k, 0 if k == 100 else 2), f"{key}.V.{name}")
    f = lambda n, k=100, plus=True: ci(D[n], plus, k, 0 if k == 100 else 2) if n in D else "--"
    crow.append(f"{lab} & {f(CN[0][0])} & {f(CN[2][0])} & {f(CN[4][0])} & {f(CN[5][0])} & {f(CN[7][0])} & {f(CN[8][0])} & {f(CN[10][0], 1)} & {f(CN[12][0], 1)} & {f(CN[13][0])} " + BS * 2)
hdr = "% generated by scripts/make_v_outputs.py from raea4/agentenv/results/v_analysis.json; do not edit"
t1 = [hdr, BS + "begin{tabular}{@{}llrrrrrrrrrrr@{}}", BS + "toprule",
      " & & " + BS + "multicolumn{5}{c}{first action (" + BS + "%)} & " + BS + "multicolumn{5}{c}{regret per episode} & " + BS * 2 + BS + "cmidrule(lr){3-7}" + BS + "cmidrule(lr){8-12}",
      "Run & Cell (variant, fault rate) & replica & oracle: replica & planner: replica & log & other tool & K2e & K2r & under-use & over-use & verdict & calls " + BS * 2,
      BS + "midrule"] + rows[:-1] + [BS + "bottomrule", BS + "end{tabular}"]
t2 = [hdr, BS + "begin{tabular}{@{}lccccccccc@{}}", BS + "toprule",
      " & " + BS + "multicolumn{2}{c}{V1: replica cost (0.10)} & " + BS + "multicolumn{2}{c}{V2: log cost 3 (0.30)} & " + BS + "multicolumn{3}{c}{V3: field list (0.10, 0.30)} & " + BS + "multicolumn{2}{c}{V4: cost episodes} " + BS * 2
      + BS + "cmidrule(lr){2-3}" + BS + "cmidrule(lr){4-5}" + BS + "cmidrule(lr){6-8}" + BS + "cmidrule(lr){9-10}",
      "Run & cost 1 $-$ cost 3 & model$-$oracle, cost 2 & log cost 3 $-$ 1 & model$-$oracle & model$-$oracle & field list $-$ sentences & K2r$-$K2e & K2r$-$K2e & as-if $-$ oracle match " + BS * 2,
      BS + "midrule"] + crow + [BS + "bottomrule", BS + "end{tabular}"]
out = [("agent_v_cells.tex", t1), ("agent_v_contrasts.tex", t2)]
kr = []
for kk, T, lab in (("kimit", "KimiT", "Kimi K3.1 Pro (thinking)"), ("kimi", "KimiN", "Kimi K3.1 Pro (non-thinking)")):
    if kk not in A or "K" not in A[kk]: continue
    o = A[kk]["K"]; D = o["contrasts"]; cell_macros(T, kk, "K", o["cells"])
    M(T + "Count", o["n"], kk + ".K.n"); M(T + "Usable", o["usable"], kk + ".K.usable"); M(T + "NoSubmit", o["no_submit"], kk + ".K.no_submit"); M(T + "Cells", len(o["cells_complete"]), kk + ".K.cells_complete")
    if o.get("pass_share") is not None: M(T + "PassShare", pc(o["pass_share"]), kk + ".K.pass_share")
    for name, mn, k in [("K1 K2r-K2e|complete cells", "Gap", 1), ("regret|complete cells", "Regret", 1), ("K2r regret|complete cells", "PlannerAll", 1), ("verdict|complete cells", "VerdictAll", 1),
                        ("K2 first replica model-oracle|0.10,0.30", "LowGap", 100), ("K2 under|0.10,0.30", "LowUnder", 1), ("K3 first replica 0.10-0.70", "Track", 100)]:
        if name in D: M(T + mn, ci(D[name], k == 100 or mn == "Gap", k, 0 if k == 100 else 2), kk + ".K." + name); M(T + mn + "Mean", num(k * D[name]["mean"], False, 0 if k == 100 else 2), kk + ".K." + name + ".mean")
    kr += [cell_row(lab if n == 0 else "", cn, c).replace(CELLN[cn][0], "0." + cn[2:]) for n, (cn, c) in enumerate(sorted(o["cells"].items()))] + [BS + "addlinespace"]
if kr:
    t3 = [hdr, BS + "begin{tabular}{@{}llrrrrrrrrrrr@{}}", BS + "toprule",
          " & & " + BS + "multicolumn{5}{c}{first action (" + BS + "%)} & " + BS + "multicolumn{5}{c}{regret per episode} & " + BS * 2 + BS + "cmidrule(lr){3-7}" + BS + "cmidrule(lr){8-12}",
          "Run & Fault rate & replica & oracle: replica & planner: replica & log & other tool & K2e & K2r & under-use & over-use & verdict & calls " + BS * 2, BS + "midrule"] + kr[:-1] + [BS + "bottomrule", BS + "end{tabular}"]
    out.append(("agent_v_kimi.tex", t3))
for name, t in out + [("nums_v.tex", [hdr] + mac)]:
    open(os.path.join(ROOT, "tables", name), "w", encoding="utf-8").write(NL.join(t) + NL)
print(len(mac), "macros")
