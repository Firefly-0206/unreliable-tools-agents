"""tables/agent_z.tex and tables/nums_z.tex from raea4/agentenv/results/z_asif.json and z_asif_soft.json
(z_asif.py, z_asif_soft.py; exploratory, post hoc). No model call.

    python paper/scripts/make_z_outputs.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
R = os.path.join(os.path.dirname(ROOT), "raea4", "agentenv", "results")
D = json.load(open(os.path.join(R, "z_asif.json"), encoding="utf-8")); S = json.load(open(os.path.join(R, "z_asif_soft.json"), encoding="utf-8"))
RUNS = [("flash", "Flash", "flash"), ("terra", "Terra", "terra (medium)"), ("sonnet", "Sonnet", "Sonnet 5.5 (high)")]
NL, BS, MINUS = chr(10), chr(92), "$-$"
SETS = ["fit_persistent", "independent", "randomised", "repeats"]; SN = {"fit_persistent": "Fit", "independent": "Indep", "randomised": "Rand", "repeats": "Rep"}


def num(x, nd=2):
    s = f"{abs(x):.{nd}f}"; return (MINUS if x < 0 and float(s) != 0 else "") + s
def g(x): return f"{x:g}"
def pc(x): return f"{100 * x:.0f}"


mac, rows = [], []
def M(name, val, src): mac.append(BS + "providecommand{" + BS + "z" + name + "}{" + str(val) + "}% src: " + src)


for key, tag, lab in RUNS:
    d, s = D[key], S[key]
    M(tag + "G", g(d["g_hat"]), f"z_asif.json:{key}.g_hat"); M(tag + "SoftG", g(s["M1"]["g"]), f"z_asif_soft.json:{key}.M1.g")
    for n in ("fit_persistent", "independent", "randomised", "repeats_majority"):
        N = {"fit_persistent": "Fit", "independent": "Indep", "randomised": "Rand", "repeats_majority": "Rep"}[n]
        M(f"{tag}Match{N}", pc(d["match"][n]), f"z_asif.json:{key}.match.{n}"); M(f"{tag}OracleMatch{N}", pc(d["oracle"][n]), f"z_asif.json:{key}.oracle.{n}")
        M(f"{tag}NeverMatch{N}", pc(d["never"][n]), f"z_asif.json:{key}.never.{n}")
    M(tag + "RegretObs", num(d["regret_obs"]), f"z_asif.json:{key}.regret_obs"); M(tag + "RegretAsif", num(d["regret_asif"]), f"z_asif.json:{key}.regret_asif")
    for n in SETS:
        M(f"{tag}LLNoise{SN[n]}", num(s["loglik"][n]["M0"]), f"z_asif_soft.json:{key}.loglik.{n}.M0"); M(f"{tag}LLPess{SN[n]}", num(s["loglik"][n]["M1"]), f"z_asif_soft.json:{key}.loglik.{n}.M1")
    rows.append(f"{lab} & {g(s['M0']['tau'])} & {g(s['M1']['g'])} & {g(s['M1']['tau'])} & "
                + " & ".join(f"{num(s['loglik'][n]['M0'])} / {num(s['loglik'][n]['M1'])}" for n in SETS)
                + f" & {g(d['g_hat'])} & {pc(d['match']['fit_persistent'])} / {pc(d['oracle']['fit_persistent'])} / {pc(d['never']['fit_persistent'])} & "
                  f"{pc(d['match']['independent'])} / {pc(d['oracle']['independent'])} / {pc(d['never']['independent'])} & {num(d['regret_obs'])} / {num(d['regret_asif'])} " + BS * 2)
hdr = "% generated by scripts/make_z_outputs.py from raea4/agentenv/results/z_asif.json, z_asif_soft.json; do not edit"
t = [hdr, BS + "begin{tabular}{@{}lrrrcccccccc@{}}", BS + "toprule",
     " & " + BS + "multicolumn{3}{c}{fitted} & " + BS + "multicolumn{4}{c}{log-likelihood per first action, noise only / pessimism + noise} & "
     + BS + "multicolumn{4}{c}{deterministic rule} " + BS * 2 + BS + "cmidrule(lr){2-4}" + BS + "cmidrule(lr){5-8}" + BS + "cmidrule(lr){9-12}",
     "Run & $" + BS + "tau_0$ & $g$ & $" + BS + "tau$ & persistent (fit) & independent & randomized & repeats & $g$ & match, persistent & match, independent & regret obs.\\ / rule " + BS * 2,
     BS + "midrule"] + rows + [BS + "bottomrule", BS + "end{tabular}"]
for name, x in (("agent_z.tex", t), ("nums_z.tex", [hdr] + mac)):
    open(os.path.join(ROOT, "tables", name), "w", encoding="utf-8").write(NL.join(x) + NL)
print(len(mac), "macros")
