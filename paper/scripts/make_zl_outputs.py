"""tables/agent_zl.tex and tables/nums_zl.tex from raea4/agentenv/results/z_asif_loss.json and z_asif_loss_m.json
(z_asif_loss.py; exploratory, post hoc, added after review). No model call.

    python paper/scripts/make_zl_outputs.py
"""
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
R = os.path.join(os.path.dirname(ROOT), "raea4", "agentenv", "results")
D = json.load(open(os.path.join(R, "z_asif_loss.json"), encoding="utf-8"))
DM = json.load(open(os.path.join(R, "z_asif_loss_m.json"), encoding="utf-8"))
RUNS = [("flash", "Flash", "flash"), ("terra", "Terra", "terra (medium)"), ("sonnet", "Sonnet", "Sonnet 5.5 (high)")]
FAM = [("g", "replica fault odds $\\times g$"), ("sev", "severe loss"), ("err", "wrong-verdict loss"), ("pri", "benign prior odds"),
       ("esc", "escalation loss"), ("lsc", "every loss"), ("sevxesc", "severe $\\times$ escalation")]
STAKES = ["sev", "err", "pri"]          # families that keep querying
CHEAP = ["esc", "lsc", "sevxesc"]       # families that can stop querying
NL, BS = chr(10), chr(92)


def pc(x): return f"{100 * x:.0f}"
def num(x): return f"{x:.2f}"
def val(v): return ", ".join(f"{x:g}" for x in v) if isinstance(v, list) else f"{v:g}"


mac, rows = [], []
def M(name, v, src): mac.append(BS + "providecommand{" + BS + "zl" + name + "}{" + str(v) + "}% src: " + src)


# behaviour: lowest replica first-call share at fault rate 0.1 and 0.3 over every value of the stake / prior families
low = min(min(b["first"][:2]) for k, b in D["behaviour"].items() if k.split("=")[0] in STAKES)
M("MinFirstLow", f"{low:.0f}", "z_asif_loss.json:behaviour[sev|err|pri=*].first[0:2] min")
for key, tag, lab in RUNS:
    o = D["runs"][key]; f = o["fits"]
    M(tag + "ObsCalls", num(o["obs"]["calls"]), f"z_asif_loss.json:runs.{key}.obs.calls")
    M(tag + "ObsEsc", pc(o["obs"]["esc"]), f"z_asif_loss.json:runs.{key}.obs.esc")
    M(tag + "ObsRegret", num(o["obs"]["regret"]), f"z_asif_loss.json:runs.{key}.obs.regret")
    M(tag + "StakeMax", pc(max(f[k]["fit_persistent"] for k in STAKES)), f"z_asif_loss.json:runs.{key}.fits[sev|err|pri].fit_persistent max")
    M(tag + "JointFit", pc(f["sevxesc"]["fit_persistent"]), f"z_asif_loss.json:runs.{key}.fits.sevxesc.fit_persistent")
    for k, nm in (("esc", "Esc"), ("lsc", "Lsc")):
        for q, Q, fn in (("calls", "Calls", num), ("esc", "Esc", pc), ("regret", "Regret", num), ("fit_persistent", "Fit", pc)):
            M(f"{tag}{nm}{Q}", fn(f[k][q]), f"z_asif_loss.json:runs.{key}.fits.{k}.{q}")
    for a in ("MF", "MZ"):
        M(f"{tag}{a}RepObs", num(DM[key][f"obs|{a}"]["rep"]), f"z_asif_loss_m.json:{key}.obs|{a}.rep")
        M(f"{tag}{a}RepMin", num(min(DM[key][f"{k}|{a}"]["rep"] for k, _ in FAM if f"{k}|{a}" in DM[key] and DM[key][f"{k}|{a}"]["calls"] > 1)),
          f"z_asif_loss_m.json:{key}.*|{a}.rep min over variants with >1 call")
    for i, (k, nm) in enumerate(FAM):
        r = f[k]
        rows.append(f"{lab if i == 0 else ''} & {nm} & {val(r['value'])} & {pc(r['fit_persistent'])} & {pc(r['independent'])} & "
                    + " / ".join(f"{100 * x:.0f}" for x in r["first"]) + f" & {num(r['calls'])} & {pc(r['esc'])} & {num(r['regret'])} " + BS * 2)
    rows.append(f" & observed &  & & & " + " / ".join(f"{100 * o['obs']['first'][f'XP|{p:.2f}']:.0f}" for p in (0.1, 0.3, 0.5, 0.7))
                + f" & {num(o['obs']['calls'])} & {pc(o['obs']['esc'])} & {num(o['obs']['regret'])} " + BS * 2)
    if key != RUNS[-1][0]: rows.append(BS + "midrule")
last = open(os.path.join(R, "z_asif_loss_m.txt"), encoding="utf-8").read().strip().splitlines()[-1]   # "oracle: MF calls a repeat b; MZ calls c repeat d"
M("OracleMZRep", last.split("MZ calls")[1].split("repeat")[1].split()[0], "z_asif_loss_m.txt: oracle line, MZ repeat")

head = ("% generated by scripts/make_zl_outputs.py from raea4/agentenv/results/z_asif_loss.json, z_asif_loss_m.json; do not edit" + NL)
open(os.path.join(ROOT, "tables", "nums_zl.tex"), "w", encoding="utf-8").write(head + NL.join(mac) + NL)
tab = (head + BS + "begin{tabular}{llrrrcrrr}" + NL + BS + "toprule" + NL
       + "Run & As-if change & Fitted & Fit & Indep & First call 0.1/0.3/0.5/0.7 (\\%) & Calls & Esc.\\ (\\%) & Regret " + BS * 2 + NL
       + BS + "midrule" + NL + NL.join(rows) + NL + BS + "bottomrule" + NL + BS + "end{tabular}" + NL)
open(os.path.join(ROOT, "tables", "agent_zl.tex"), "w", encoding="utf-8").write(tab)
print(f"{len(mac)} macros, {len(rows)} rows")
